# mkinject.py <stock crec.bin> <other crec.bin> <out .h> <index> [<index> ...]: bench (round 50) -- the
# player car's state at the given record indices of a stock run, as a header for A4_BENCH_INJECT
# (a4_gl.c car_record): at those steps a build overwrites its player car with stock's, so stock and the
# 3x engine continue from one state and their next steps compare like for like. Words kept from the
# live car (never injected): the vtable (+000), the owner block (+140..+16F), and every word that holds
# a heap or code address in either run (they differ between builds: the allocations do).
import sys, os
sys.argv = [sys.argv[0]] + sys.argv[1:]
src = open(os.path.join(os.path.dirname(os.path.abspath(__file__)), 'oracle.py')).read().split('A = series')[0]
args = sys.argv[1:]; sys.argv = sys.argv[:1]
g = {'__file__': os.path.abspath(__file__)}; exec(src, g)
A = g['load'](args[0]); B = g['load'](args[1]); out = args[2]; idx = [int(x) for x in args[3:]]
NW = 0xC7C // 4
keep = set([0]) | set(range(0x140 // 4, 0x170 // 4))
def addr(v):
    v &= 0xFFFFFFFF
    return 0x02000000 <= v < 0x04000000 or 0x70000000 <= v < 0x80000000
for i in range(0, min(len(A), len(B)), 7):
    wa, wb = A[i][1], B[i][1]
    for k in range(min(NW, len(wa), len(wb))):
        if wa[k] != wb[k] and (addr(wa[k]) or addr(wb[k])): keep.add(k)
mask = [0] * ((NW + 31) // 32)
for k in keep: mask[k >> 5] |= 1 << (k & 31)
L = ['/* generated by tools/mkinject.py (bench only): stock\'s player car at record indices %s of %s */' % (idx, os.path.basename(args[0])),
     '#define A4_INJ_N %du' % len(idx), '#define A4_INJ_W %du' % NW,
     'static const uint32_t a4_inj_step[A4_INJ_N] = { %s };' % ', '.join('%du' % (i + 1) for i in idx),
     'static const uint32_t a4_inj_keep[%d] = { %s };' % (len(mask), ', '.join('0x%08Xu' % m for m in mask)),
     'static const uint32_t a4_inj_car[A4_INJ_N][A4_INJ_W] = {']
for i in idx:
    w = A[i][1]
    assert len(w) >= NW, 'record %d has %d words' % (i, len(w))
    L.append('  { ' + ', '.join('0x%Xu' % (x & 0xFFFFFFFF) for x in w[:NW]) + ' },')
L.append('};')
open(out, 'w').write('\n'.join(L) + '\n')
print('%s: %d states, %d words kept live' % (out, len(idx), len(keep)))
