// the last partial block dies with the process, so the first run under it
// could only say the fault was somewhere in a window of sixty-three events.
// Eight narrows that to seven and still writes only a few hundred times over a
// run of thousands, well under the ceiling.
// Events per write of the log. Every one of them while the run is young, where
// the fault has been landing and a window of even eight events is too wide to
// name a call; then one write per sixteen, which keeps a run of thousands well
// under the two thousand writes that used to end it in a reboot.
// Every write to the record costs the same scarce thing: this process gets
// about two thousand RFile::Write calls out of the phone before the file
// server takes it down with it, so the record's cadence is the run's length.
// Sixty-four events to a write buys ten times the run the exact cadence did.
// LOG_ZOOM..LOG_ZOOM_END is a window the record is written event by event
// through, so a run that died somewhere inside a block can be watched closely
// over just that block and stay cheap everywhere else. Past the end of the run
// for both means the whole thing runs at the block cadence.
// Over the run's last stretch, event by event. Two runs have ended at a block
// boundary in this region, which says only that the fault is somewhere in the
// sixty-odd events after it -- not, as it first looked, at the call the last
// record names. About 250 extra writes, which the budget takes easily.
// 1850 was too late: the phone stopped at 1853 imports and only three events
// fell inside it. The runs so far end between 1853 and 2051, so the window
// wants to open well before that and stay narrow enough to be cheap.
// Eight, not sixty-four: with the milestone trace the whole run is about two
// hundred records, so this is twenty-five writes and at most seven events lost
// if it stops. Writes were never what cost the game its reach.
//
// And the window is open again, because the one thing four reboots in a row
// have not said is *where*. The phone's last three runs end at 224, 226 and
// 265 records, which is around the hundredth traced event, and with eight
// events to a block the last record written is up to seven events before the
// one that killed it -- which is exactly the ambiguity that let 0xe4774 be
// named as the guilty caller when it was 0xed694. Opening at 65 leaves the
// last third of the run recorded event by event, for about eighty extra
// writes. The build that took the phone down through sheer write volume did
// around two thousand.
//
// SILENT: the instrument has been the bug twice, and the run that recorded
// most also died soonest. Rather than keep guessing at the right weight, this
// build takes the weight to nearly nothing -- one write, at the end, if the
// end is ever reached -- and asks the only question that settles it: does the
// phone still go down when almost nothing is being written? Everything the
