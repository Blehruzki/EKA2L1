static const u32 *vtable_of(const u32 *object)
{
    return (const u32 *)object[0] - VT_HEADER;
}

static u32 *copy_vtable(const u32 *real, int slots)
{
    u32 *vt = (u32 *)user_allocz((VT_HEADER + slots) * 4);
    if (!vt) PANIC(CAT_MEM, -30);
    for (int i = 0; i < VT_HEADER + slots; i++)
        vt[i] = real[i];
    return vt;
}

// The other direction. When the game calls a framework method on itself, the
// 9.x implementation must not see the old object, so the call is diverted to
// one of ours -- which needs the context, and gets it in r2:
//
//   ldr r2, [pc, #4]    @ the context, baked in when the stub is built
//   ldr pc, [pc, #4]    @ and on to our implementation
//   .word context
//   .word our function
//
// r0 and r1 pass through untouched, so the old arguments arrive as they were.
static u32 ctx_thunk(u8 *code, const void *ctx, u32 target)
{
    u32 *b = (u32 *)code;
    b[0] = 0xE59F2004;                  // ldr r2, [pc, #4]
    b[1] = 0xE59FF004;                  // ldr pc, [pc, #4]
    b[3] = (u32)ctx;
    b[4] = target;
    user_imb_range(b, b + 5);
    return (u32)b;
}

// The same, for a call that already uses r0 to r2.
//
//   ldr r3, [pc, #4]
//   ldr pc, [pc, #4]
static u32 ctx3_thunk(u8 *code, const void *ctx, u32 target)
{
    u32 *b = (u32 *)code;
    b[0] = 0xE59F3004;
    b[1] = 0xE59FF004;
    b[3] = (u32)ctx;
    b[4] = target;
    user_imb_range(b, b + 5);
    return (u32)b;
}

// The simpler diversion: the 9.x implementation is the right one, it just must
// not be handed the old object. The wrapper does not exist when the stub is
// built, so the thunk reads it from the context each time:
//
//   ldr rN, [pc, #8]    @ rN = the cell holding the wrapper
//   ldr rN, [rN]
//   ldr pc, [pc, #4]
//   .word cell
//   .word the 9.x function
static u32 this_thunk(u8 *code, const void *cell, u32 target, int reg)
{
    u32 *b = (u32 *)code;
    b[0] = 0xE59F0008 | ((u32)reg << 12);           // ldr rN, [pc, #8]
    b[1] = 0xE5900000 | ((u32)reg << 16) | ((u32)reg << 12);
    b[2] = 0xE59FF004;                              // ldr pc, [pc, #4]
    b[4] = (u32)cell;
    b[5] = target;
    user_imb_range(b, b + 6);
    return (u32)b;
}

// A phone reports a fault as KERN-EXEC 3 and nothing else -- no address, no
// instruction. So every import the game makes goes through this first, which
// records which one it was and jumps on. r0 and r12 are saved across the
// record; lr is the caller's and is never touched, and neither are the flags.
//
//   stmdb sp!, {r0, r12}
//   ldr   r0, [pc, #12]     @ where to record it
//   ldr   r12, [pc, #12]    @ which import
//   str   r12, [r0]
//   ldmia sp!, {r0, r12}
//   ldr   pc, [pc, #4]      @ and on to whatever answers it
enum { TRACE = 48 };

extern "C" void gate6_trace(u32 index, Context *c, u32 caller);
extern "C" void gate6_slot(u32 code, Context *c, u32 caller);

// Records `value` through `note` and carries on to `target`, leaving every
// argument register as it found them. lr still holds the caller's return
// address when the note is made, which is how a trace says where a call came
// from and not only what it was.
static u32 trace_thunk(u8 *code, const void *ctx, u32 value, u32 target, u32 note)
{
    u32 *b = (u32 *)code;
    b[0] = 0xE92D500F;                  // stmdb sp!, {r0-r3, r12, lr}  -- 24 bytes, aligned
    b[1] = 0xE59F0014;                  // ldr   r0, [pc, #20]   -- which import
    b[2] = 0xE59F1014;                  // ldr   r1, [pc, #20]   -- the context
    b[3] = 0xE59FC014;                  // ldr   r12, [pc, #20]
    b[4] = 0xE1A0200E;                  // mov   r2, lr          -- who called
    b[5] = 0xE12FFF3C;                  // blx   r12
    b[6] = 0xE8BD500F;                  // ldmia sp!, {r0-r3, r12, lr}
    b[7] = 0xE59FF008;                  // ldr   pc, [pc, #8]
    b[8] = value;
    b[9] = (u32)ctx;
    b[10] = note;
    b[11] = target;
    user_imb_range(b, b + 12);
    return (u32)b;
}

// Then a fault says where it happened, in the only terms the phone gives us.
extern "C" void gate6_fault(Context *c, int type)
{
    PANIC(CAT_FLT, (int)(c->lastImport * 100 + (u32)(type & 63)));
}

// Both at once, for a call that is given one wrapper and made on another. Five
// instructions and three words is exactly the slot, with nothing to spare.
static u32 pair_thunk(u8 *code, const void *cell0, const void *cell1, u32 target)
{
    u32 *b = (u32 *)code;
    b[0] = 0xE59F000C;                  // ldr r0, [pc, #12]
    b[1] = 0xE5900000;                  // ldr r0, [r0]
    b[2] = 0xE59F1008;                  // ldr r1, [pc, #8]
    b[3] = 0xE5911000;                  // ldr r1, [r1]
    b[4] = 0xE59FF004;                  // ldr pc, [pc, #4]
    b[5] = (u32)cell0;
    b[6] = (u32)cell1;
    b[7] = target;
    user_imb_range(b, b + 8);
    return (u32)b;
}

// Once the game has its own copy of the environment it also calls cone on it,
// and a copy is not something cone can be handed. So the calls go back to the
// real one -- and the observer that goes with this one is a GCC98r2 mixin,
// which a 9.x caller cannot use, so it gets the same two-slot stand-in the
// direct screen access observer gets.
//
//   ldr r12, [pc, #16]      @ where to keep the game's observer
//   str r1, [r12]
//   ldr r12, [pc, #12]      @ the real environment
//   ldr r0, [r12]
//   ldr r1, [pc, #8]        @ ours
//   ldr pc, [pc, #8]
static u32 fg_thunk(u8 *code, const void *savedCell, const void *envCell,
                    const void *observer, u32 target)
{
    u32 *b = (u32 *)code;
    b[0] = 0xE59FC010;
    b[1] = 0xE58C1000;
    b[2] = 0xE59FC00C;
    b[3] = 0xE59C0000;
    b[4] = 0xE59F1008;
    b[5] = 0xE59FF008;
    b[6] = (u32)savedCell;
    b[7] = (u32)envCell;
    b[8] = (u32)observer;
    b[9] = target;
    user_imb_range(b, b + 10);
    return (u32)b;
}

