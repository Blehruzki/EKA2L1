// the log dying, silently, because nothing here ever looked at what
// file_write_at returned: the position advances whether or not the write
// landed, so a file server that starts refusing leaves the file at 512 bytes
// and the run carries on blind. The box stops at the same moment for the same
// reason, which is why those runs look like they ended at event nine.
//
// So the error is no longer discarded. The first one panics with its own code,
// which is a number the phone puts on screen -- the run was already over as
// far as the record goes, and this way it says why.
static void log_block(Context *c)
{
    if (!c->logFill || !c->logFile[0])
        return;
    c->logDes[0] = ((u32)EPtrC << KTypeShift) | (c->logFill * 8);
    c->logDes[1] = (u32)c->logBuf;
    const i32 err = file_write_at(c->logFile, (int)c->logPos, c->logDes);
    if (LOUD_WRITE_ERRORS && err)
        PANIC(CAT_WRITE, (int)err);
    file_flush(c->logFile);
    c->logPos += c->logFill * 8;
    c->logFill = 0;
    // The summary used to go out at the same cadence, which doubled the cost of
    // every block for a file nothing reads any more now that the log survives
    // the run. It is written once at the start and at the exits instead.
}

static void log_event(Context *c, u32 code, u32 from)
{
    if (c->logFill < LOG_BLOCK) {
        c->logBuf[c->logFill * 2] = code;
        c->logBuf[c->logFill * 2 + 1] = from;
        c->logFill++;
    }
    // Exact over the opening, blocks after it. The short runs all end with the
    // log at sixty-four records, which is eight full blocks of eight -- a
    // boundary of our own making, not a sector, and it hides the last seven
    // records. Every record is written on its own until the file passes
    // EXACT_BYTES, which costs about seventy writes and puts the true last
    // record on disk.
    const u32 n = c->traceCount;
    const u32 want = (c->logPos < (u32)EXACT_BYTES) ? 1u
                   : (n >= (u32)LOG_ZOOM && n < (u32)LOG_ZOOM_END) ? 1u
                   : (u32)LOG_BLOCK;
    if (c->logFill >= want)
        log_block(c);
}

