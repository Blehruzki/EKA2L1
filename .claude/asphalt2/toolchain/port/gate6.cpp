// On C: rather than the memory card. Two reasons: the card is the one piece of
// this the phone has a removable driver for, and internal flash answers a
// flush faster, which is what lets every record be flushed again.
static const u16 kBoxPath[] = {'C',':','\\','g','6','b','o','x','.','d','a','t'};

// A record left by a different build is worse than no record: it reads back as
// a plausible number and says nothing. So the file carries what wrote it.
enum { BOX_MAGIC = 0x47364234 };        // "G6B4"
enum { BOX_NONE = 0xFFFFFFFF, BOX_ARMED = 0xFFFFFFFE };
enum { EFileWrite = 0x200, EFileShareAny = 0x30 };

static void box_name(Ptrc16 *name)
{
    name->lengthAndType = ((u32)EPtrC << KTypeShift) | (u32)(sizeof kBoxPath / 2);
    name->text = kBoxPath;
}

// Writing is cheap enough to do on every import; it is the flush that costs,
// and the file server still has what was written when the process dies.
// The one thing a fault leaves no trace of is how much room it had left. Every
// marker notes where the stack had got to, and the record carries the deepest.
static void stack_mark(Context *c)
{
    const u32 sp = (u32)__builtin_frame_address(0);
    if (!c->spTop) c->spTop = sp;
    if (sp < c->spLow || !c->spLow) c->spLow = sp;
}

static void box_write(Context *c)
{
    c->boxData[0] = BOX_MAGIC;
    c->boxData[1] = c->lastImport;
    c->boxData[2] = c->reached;
    c->boxData[3] = c->traceCount;
    c->boxData[BOX_PATH] = c->pathIndex;
    c->boxData[BOX_SLOT] = c->lastCall;
    c->boxData[BOX_FRAMES] = c->frames;
    c->boxData[BOX_STACK] = c->spTop - c->spLow;
    c->boxDes[0] = ((u32)EPtrC << KTypeShift) | BOX_BYTES;
    c->boxDes[1] = (u32)c->boxData;
    file_write_at(c->boxFile, 0, c->boxDes);
}

static void box_flush(Context *c)
{
    box_write(c);
    file_flush(c->boxFile);
}

static const u16 kTextPath[] = {'C',':','\\','g','6','b','o','x','.','t','x','t'};

static int put_hex(u8 *out, u32 v)
{
    u8 digits[8];
    int n = 0;
    do { const u32 d = v & 0xF; digits[n++] = (u8)(d < 10 ? '0' + d : 'a' + d - 10); v >>= 4; }
    while (v);
    for (int i = 0; i < n; i++) out[i] = digits[n - 1 - i];
    return n;
}

static int put_u32(u8 *out, u32 v)
{
    u8 digits[10];
    int n = 0;
    do { digits[n++] = (u8)('0' + v % 10); v /= 10; } while (v);
    for (int i = 0; i < n; i++) out[i] = digits[n - 1 - i];
    return n;
}

// A panic carries one number. This carries the whole tail, in a file the phone
// can open: how many imports went past, which one it was on, what had happened
// and, oldest first, the last sixteen imports the game made. Written on the
// launch after the one that stopped, beside the record it is made from.
static void box_report(Context *c, u32 count)
{
    u8 text[1024];
    int n = 0;
    const u8 kSteps[] = { 's','t','e','p','s',' ' };
    const u8 kLast[] = { '\n','l','a','s','t',' ' };
    const u8 kFlags[] = { '\n','f','l','a','g','s',' ' };
    const u8 kPath[] = { '\n','p','a','t','h',' ' };
    const u8 kTail[] = { '\n','t','a','i','l' };
    for (u32 i = 0; i < sizeof kSteps; i++) text[n++] = kSteps[i];
    n += put_u32(text + n, count);
    for (u32 i = 0; i < sizeof kLast; i++) text[n++] = kLast[i];
    n += put_u32(text + n, c->boxData[1]);
    for (u32 i = 0; i < sizeof kFlags; i++) text[n++] = kFlags[i];
    n += put_u32(text + n, c->boxData[2]);
    for (u32 i = 0; i < sizeof kPath; i++) text[n++] = kPath[i];
    n += put_u32(text + n, c->boxData[BOX_PATH]);
    for (u32 i = 0; i < sizeof kTail; i++) text[n++] = kTail[i];
    for (u32 i = 0; i < BOX_RING; i++) {
        text[n++] = ' ';
        n += put_u32(text + n, c->boxData[4 + ((count + i) & (BOX_RING - 1))]);
    }
    const u8 kSlot[] = { '\n','s','l','o','t',' ' };
    for (u32 i = 0; i < sizeof kSlot; i++) text[n++] = kSlot[i];
    n += put_hex(text + n, c->boxData[BOX_SLOT]);
    const u8 kFrames[] = { '\n','f','r','a','m','e','s',' ' };
    for (u32 i = 0; i < sizeof kFrames; i++) text[n++] = kFrames[i];
    n += put_u32(text + n, c->boxData[BOX_FRAMES]);
    const u8 kStack[] = { '\n','s','t','a','c','k',' ' };
    for (u32 i = 0; i < sizeof kStack; i++) text[n++] = kStack[i];
    n += put_u32(text + n, c->boxData[BOX_STACK]);
    const u8 kHits[] = { '\n','h','i','t','s' };
    for (u32 i = 0; i < sizeof kHits; i++) text[n++] = kHits[i];
    for (u32 i = 0; i < BOX_MARKERS; i++) {
        text[n++] = ' ';
        n += put_u32(text + n, c->boxData[BOX_HITS + i]);
    }
    const u8 kFrom[] = { '\n','f','r','o','m' };
    for (u32 i = 0; i < sizeof kFrom; i++) text[n++] = kFrom[i];
    for (u32 i = 0; i < BOX_RING; i++) {
        text[n++] = ' ';
        n += put_hex(text + n, c->boxData[BOX_FROM + ((count + i) & (BOX_RING - 1))]);
    }
    text[n++] = '\n';

    u32 file[4] = { 0, 0, 0, 0 };
    Ptrc16 name;
    name.lengthAndType = ((u32)EPtrC << KTypeShift) | (u32)(sizeof kTextPath / 2);
    name.text = kTextPath;
    if (file_replace(file, c->boxFs, &name, EFileWrite | EFileShareAny) == 0) {
        u32 des[2];
        des[0] = ((u32)EPtrC << KTypeShift) | (u32)n;
        des[1] = (u32)text;
        file_write_at(file, 0, des);
        file_flush(file);
        rhandle_close(file);
    }
}

// The trace itself does the recording, because the crash we are after happens
// while the framework is still starting the application up and the active
// scheduler has not run yet -- a timer never gets a turn. Every import goes
// through here; every so many of them reach the disk.
enum { BOX_EVERY = 16 };
// How many records go by between flushes. Thinning this was a mistake: a write
// that has not been flushed is still in the file server when the phone goes
// down, and goes down with it, so the record was reading up to sixty-three
// events stale exactly when it mattered. Back to every one.
enum { BOX_SETTLE = 1 };
enum { REACHED_LEAVE = 64, REACHED_EXIT = 128 };  // how the game ended, if it did

// The emulator hears RDebug, and a phone does not, which makes this the one
// instrument that can say what happened in what order rather than only what
// happened last. "G6 01cc" is import 460; "G6+0504" is a call into one of our
// own slots.
// Every import is a lot of them; a phone would spend real time on it, so the
// per-import half is one constant away from being off.
enum { TRACE_IMPORTS = 0 };

static void note(Context *c, u32 value, u16 sign)
{
    u16 *b = (u16 *)c->noteText;
    b[0] = 'G';
    b[1] = '6';
    b[2] = sign;
    for (int i = 0; i < 4; i++) {
        const u32 d = (value >> (12 - 4 * i)) & 0xF;
        b[3 + i] = (u16)(d < 10 ? '0' + d : 'a' + d - 10);
    }
    c->noteDes[0] = ((u32)EPtrC << KTypeShift) | 7;
    c->noteDes[1] = (u32)c->noteText;
    rdebug_rawprint(c->noteDes);
}

// The phone goes down inside the obfuscated state machine at 0xc9cd4, between
// one import and the next, so the record has nothing to say about where. A
// breadcrumb is a marker planted at an address in the game: the instruction
// there is replaced with a branch to a stub that records which one was
// reached, puts the flags and registers back, runs the instruction it
// displaced, and returns to what followed it. These seventeen are the cases of
// that machine's jump table, which is as fine a grain as its own structure
// offers. Two of them read the program counter and cannot be moved, so they
// are left alone and never report.
enum { CRUMB_BYTES = 80, CRUMB_FIRST = 900 };
static const u32 kCrumb[] = {
    // The seventeen cases of the machine's jump table.
    0x0c9d84, 0x0c9dc0, 0x0ca470, 0x0c9e2c, 0x0c9e38, 0x0c9e44, 0x0c9e6c,
    0x0c9fb0, 0x0ca014, 0x0ca168, 0x0ca1d0, 0x0ca238, 0x0ca29c, 0x0ca2c4,
    0x0ca2e0, 0x0ca2fc, 0x0ca390,
    // And through the body of case 8, every forty bytes or so. Case 9 hands
    // to case 8 -- each case ends by loading a state and re-entering the
    // dispatcher, so the sequence reads straight out of the literals -- and
    // case 8 is where the phone stops reporting. It is also the one case whose
    // first instruction reads the program counter, which is why nothing was
    // planted in it the first time round.
    0x0ca038, 0x0ca060, 0x0ca088, 0x0ca0b0, 0x0ca0d8, 0x0ca100,
    0x0ca128, 0x0ca150,
    // And two that cut the remaining gap in three: the tail of case 9, and
    // the dispatcher every case returns to. 926 without 927 says it died in
    // case 9's own body; 927 without 917 says it died getting out of the
    // jump table.
    0x0ca1b4, 0x0c9d20,
    // Case 9's body is eighteen instructions of stack traffic and arithmetic,
    // and the phone dies somewhere inside it. One marker every few
    // instructions says which.
    0x0ca170, 0x0ca178, 0x0ca180, 0x0ca1a4, 0x0ca1ac, 0x0ca1b0,
};

// An instruction can only be moved if it does not depend on where it is.
static int crumb_safe(u32 w)
{
    if ((w >> 28) != 0xE) return 0;             // only the unconditional ones
    const u32 cls = (w >> 25) & 7;
    if (cls >= 5) return 0;                     // branches, coprocessor, SWI
    if (((w >> 16) & 0xF) == 15) return 0;      // reads the program counter
    if (((w >> 12) & 0xF) == 15) return 0;      // or writes it
    if ((cls == 0 || cls == 3) && (w & 0xF) == 15) return 0;
    if (cls == 4 && (w & 0x8000)) return 0;     // or carries it in a list
    return 1;
}

// User::Leave and User::Exit are where the game gives up, so those two say
// where from as well.
enum { IMPORT_LEAVE = 324, IMPORT_EXIT = 308 };

// A breadcrumb goes into the same ring as the imports, so the two interleave
// and the order is the order things happened in. The marker reads as 900 and
// up, which no import index does, and the caller column carries where it was
// planted.
extern "C" void gate6_crumb(u32 marker, Context *c, u32 site)
{
    stack_mark(c);
    if (marker - CRUMB_FIRST < BOX_MARKERS)
        c->boxData[BOX_HITS + (marker - CRUMB_FIRST)]++;
    c->lastImport = marker;
    const u32 slot = c->traceCount & (BOX_RING - 1);
    c->boxData[4 + slot] = marker;
    c->boxData[BOX_FROM + slot] = site;
    c->traceCount++;
    if ((c->traceCount % BOX_SETTLE) == 0) box_flush(c); else box_write(c);
}

//   stmdb sp!, {r0-r3, r12, lr}
//   mrs   r0, cpsr
//   stmdb sp!, {r0, r1}
//   ldr   r0, [pc, #36]     @ which one
//   ldr   r1, [pc, #36]     @ the context
//   ldr   r2, [pc, #36]     @ where it ended up being planted
//   ldr   r12, [pc, #36]
//   blx   r12
//   ldmia sp!, {r0, r1}
//   msr   cpsr_f, r0
//   ldmia sp!, {r0-r3, r12, lr}
//   <the instruction that used to be there>
//   ldr   pc, [pc, #-4]     @ and on with the rest of it
// Where the named instruction cannot be moved, the next few are tried: a
// prologue runs straight through, so a marker a little further in says the
// same thing. The search stops at anything that branches, since past that the
// marker would no longer mean the case was entered.
static void crumb_plant(Context *c, u8 *base, u32 at, u32 marker)
{
    u32 *site = 0;
    u32 original = 0;
    for (u32 i = 0; i < 8; i++) {
        u32 *p = (u32 *)(base + at + 4 * i);
        if (crumb_safe(*p)) { site = p; original = *p; break; }
        if (((*p >> 25) & 7) >= 5) break;       // a branch: go no further
    }
    if (!site || c->spare + CRUMB_BYTES > c->spareEnd)
        return;
    u32 *b = (u32 *)c->spare;
    c->spare += CRUMB_BYTES;
    b[0] = 0xE92D500F;  b[1] = 0xE10F0000;  b[2] = 0xE92D0003;
    b[3] = 0xE59F0024;  b[4] = 0xE59F1024;  b[5] = 0xE59F2024;
    b[6] = 0xE59FC024;  b[7] = 0xE12FFF3C;  b[8] = 0xE8BD0003;
    b[9] = 0xE128F000;  b[10] = 0xE8BD500F; b[11] = original;
    b[12] = 0xE51FF004; b[13] = (u32)(site + 1);
    b[14] = marker;     b[15] = (u32)c;
    b[16] = (u32)site - (u32)base;
    b[17] = (u32)&gate6_crumb;
    user_imb_range(b, b + 18);
    *site = 0xEA000000 | ((((u32)b - (u32)site - 8) >> 2) & 0x00FFFFFF);
    user_imb_range(site, site + 1);
}

extern "C" void gate6_trace(u32 index, Context *c, u32 caller)
{
    stack_mark(c);
    if (TRACE_IMPORTS)
        note(c, index, ' ');
    if (index == IMPORT_LEAVE || index == IMPORT_EXIT) {
        c->reached |= (index == IMPORT_LEAVE) ? REACHED_LEAVE : REACHED_EXIT;
        note(c, caller >> 16, 'R');
        note(c, caller & 0xFFFF, 'r');
        box_flush(c);
    }
    c->lastImport = index;
    const u32 slot = c->traceCount & (BOX_RING - 1);
    c->boxData[4 + slot] = index;
    c->boxData[BOX_FROM + slot] = caller - c->codeBase;
    // Every import is written, which costs the file server a message and the
    // card nothing. Flushing is what reaches the card, so it happens rarely.
    ++c->traceCount;
    if ((c->traceCount % BOX_SETTLE) == 0)
        box_flush(c);
    else
        box_write(c);
}

// The framework calling one of our objects. Rare enough to write out every
// time, so the record is exact rather than to the nearest sixteen.
enum { REACHED_SLOT = 16 };

extern "C" void gate6_slot(u32 code, Context *c, u32)
{
    note(c, code, '+');
    c->lastCall = code;
    c->reached |= REACHED_SLOT;         // so a zero can be told from a silence
    box_flush(c);
}

// Every slot of a wrapper's vtable, so that whatever the framework does to it
// last is on record. The object is named in the top byte.
enum { OBJ_APP = 1, OBJ_DOC = 2, OBJ_UI = 3, OBJ_CONTROL = 4, OBJ_TIMER = 5 };

static void instrument(Context *c, u32 *vt, int slots, u32 object)
{
    for (int i = 0; i < slots; i++) {
        if (c->spare + TRACE > c->spareEnd)
            return;
        vt[VT_HEADER + i] = trace_thunk(c->spare, c, (object << 8) | (u32)i,
                                        vt[VT_HEADER + i], (u32)&gate6_slot);
        c->spare += TRACE;
    }
}

// There was a timer here that flushed the record every five milliseconds. It
// was written before every import wrote its own record, when the worry was a
// fault arriving long after the last import; it has been redundant since, and
// it was doing two hundred RFile::Flush calls a second to a memory card for as
// long as the game ran. On a host file that costs nothing, which is why the
// emulator never minded. Every one of those flushes commits to the card on a
// phone, and the reboots -- hardware only, asynchronous, no panic, no leave,
// always at about the same point because the game takes about the same time to
// get there -- fit that and nothing in the game's own code.
static void box_start(Context *) {}

// ---- the timer -------------------------------------------------------------

typedef void *(*TimerCtor)(void *self, int priority);

// Which of the ways back into the game have been taken. A phone can report one
// number and only once, so the ones that must not stop are recorded and the one
// under test carries the record out with it.
enum { REACHED_ABORT = 1, REACHED_RESTART = 2, REACHED_DOCANCEL = 4, REACHED_RUNERROR = 8 };
enum { REACHED_RUNL = 32 };   // the frame loop ran at least once

extern "C" void gate6_timer_docancel(void *, u32, Context *c)
{
    c->reached |= REACHED_DOCANCEL;
    old_call(c->oldTimer, OLD_DOCANCEL);
}

static void dsa_refresh(Context *c);

extern "C" void gate6_timer_runl(void *, u32, Context *c)
{
    c->reached |= REACHED_RUNL;
    c->frames++;

    // The request completed into the wrapper, and the game reads the result out
    // of its own object, so carry it across before handing over.
    c->oldTimer[ACTIVE_STATUS / 4] = c->wrapTimer[ACTIVE_STATUS / 4];
    c->oldTimer[ACTIVE_ACTIVE / 4] = c->wrapTimer[ACTIVE_ACTIVE / 4];

    // The frame the game is about to draw reads the direct screen access
    // object, so its view of it is brought up to date first.
    dsa_refresh(c);

    old_call(c->oldTimer, OLD_RUNL);
}

extern "C" u32 gate6_timer_runerror(void *, u32 error, Context *c)
{
    c->reached |= REACHED_RUNERROR;
    return old_call1(c->oldTimer, OLD_RUNERROR, error);
}

extern "C" void gate6_request_complete(u32 **status, int reason, Context *c)
{
    typedef void (*RequestComplete)(u32 **, int);
    if (c->oldTimer && c->wrapTimer &&
        *status == (u32 *)((u8 *)c->oldTimer + ACTIVE_STATUS))
        *status = (u32 *)((u8 *)c->wrapTimer + ACTIVE_STATUS);
    ((RequestComplete)c->newRequestComplete)(status, reason);
}

// The game constructs its CTimer; ours is constructed alongside it, and from
// here on everything the game does to its own goes to ours instead. A GCC98r2
// constructor returns the object, which is still the game's.
extern "C" void *gate6_ctimer_ctor(u32 *oldSelf, int priority, Context *c)
{
    c->oldTimer = oldSelf;

    u32 *t = (u32 *)user_allocz(WRAP_BYTES);
    if (!t) PANIC(CAT_MEM, -35);
    ((TimerCtor)c->newTimerCtor)(t, priority);

    u32 *vt = copy_vtable(vtable_of(t), TIMER_SLOTS);
    vt[VT_HEADER + NEW_DOCANCEL] = c->timerThunks[0];
    vt[VT_HEADER + NEW_RUNL] = c->timerThunks[1];
    vt[VT_HEADER + NEW_RUNERROR] = c->timerThunks[2];
    instrument(c, vt, TIMER_SLOTS, OBJ_TIMER);
    t[0] = (u32)(vt + VT_HEADER);

    c->wrapTimer = t;
    return oldSelf;
}

