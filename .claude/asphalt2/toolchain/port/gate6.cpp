static void box_write(Context *c)
{
    // The same guard log_block has had all along, and the box never did.
    //
    // If `file_replace` of the box fails, `boxFile` stays zero and every write
    // after it is `RFile::Write` on handle 0 -- which is **KERN-EXEC 0, a bad
    // handle**. The phone has raised one of those every run for dozens of
    // rounds, and round 54 showed why it was never in a log: it is the second
    // launch of the pair, and it dies at the first box write, two records in.
    if (!c->boxFile[0])
        return;
    c->boxData[0] = BOX_MAGIC;
    c->boxData[1] = c->lastImport;
    c->boxData[2] = c->reached;
    c->boxData[3] = c->traceCount;
    c->boxData[BOX_PATH] = c->pathIndex;
    c->boxData[BOX_SLOT] = c->lastCall;
    c->boxData[BOX_FRAMES] = c->frames;
    c->boxData[BOX_STACK] = c->spTop - c->spLow;
    c->boxDes[0] = ((u32)EPtrC << KTypeShift) | BOX_BYTES;
    c->boxDes[1] = (u32)c->boxData;
    const i32 err = file_write_at(c->boxFile, 0, c->boxDes);
    if (LOUD_WRITE_ERRORS && err)
        PANIC(CAT_BOXW, (int)err);
}

static void box_flush(Context *c)
{
    // Guard both calls, not just the write. Build 55 put the guard inside
    // box_write and left this flush unguarded, so a failed box replace still
    // ended in `RFile::Flush` on handle 0 -- the same bad handle, one line
    // further down. The stub launch went from two records to four and then
    // died in exactly the same place, which is what a half-applied fix looks
    // like.
    if (!c->boxFile[0])
        return;
    box_write(c);
    file_flush(c->boxFile);
}

