// A breadcrumb goes into the same ring as the imports, so the two interleave
// and the order is the order things happened in. The marker reads as 900 and
// up, which no import index does, and the caller column carries where it was
// planted.
// A breadcrumb that also carries r5. The stub's `mov r3, r5` runs after the
// registers are saved and before the call, so the value is the game's own at
// the moment it passed the site -- which is how a list walk is followed: one
// record per node, and the node is in it.
extern "C" void gate6_crumb(u32 marker, Context *c, u32 site);

extern "C" void gate6_crumb_r5(u32 marker, Context *c, u32 site, u32 r5)
{
    gate6_crumb(marker, c, site);
    log_event(c, NOTE_R5, r5);
    // And the first four words of whatever it points at, when that is an
    // address this process could plausibly own: the question at the node is
    // always what is in it, not only where it is.
    if (r5 >= 0x400000 && r5 < 0x10000000 && !(r5 & 3))
        for (u32 i = 0; i < 4; i++)
            log_event(c, NOTE_R5_AT, ((const u32 *)r5)[i]);
    log_block(c);
}

extern "C" void gate6_crumb(u32 marker, Context *c, u32 site)
{
    stack_mark(c);
    if (marker - CRUMB_FIRST < BOX_MARKERS)
        c->boxData[BOX_HITS + (marker - CRUMB_FIRST)]++;
    c->lastImport = marker;
    const u32 slot = c->traceCount & (BOX_RING - 1);
    c->boxData[4 + slot] = marker;
    c->boxData[BOX_FROM + slot] = site;
    c->traceCount++;
    log_event(c, marker, site);
}

//   stmdb sp!, {r0-r3, r12, lr}
//   mrs   r0, cpsr
//   stmdb sp!, {r0, r1}
//   ldr   r0, [pc, #36]     @ which one
//   ldr   r1, [pc, #36]     @ the context
//   ldr   r2, [pc, #36]     @ where it ended up being planted
//   ldr   r12, [pc, #36]
//   blx   r12
//   ldmia sp!, {r0, r1}
//   msr   cpsr_f, r0
//   ldmia sp!, {r0-r3, r12, lr}
//   <the instruction that used to be there>
//   ldr   pc, [pc, #-4]     @ and on with the rest of it
// Where the named instruction cannot be moved, the next few are tried: a
// prologue runs straight through, so a marker a little further in says the
// same thing. The search stops at anything that branches, since past that the
// marker would no longer mean the case was entered.
// Same stub with `mov r3, r5` inserted before the call, so the handler is
// handed the register as a fourth argument. The literals move by one word.
// A thunk that lets the call happen and then records what came back, which a
// trace on the way in cannot do. Used on the allocators, to find which
// allocation produced an object the game later walks.
// One line of the watched field, from wherever it is called. The field lives
// in the game's memory at a fixed address once the first probe has named it,
// and every wrapped import is a station we already own -- no game byte is
// patched to get one, which is the whole point after 0xe9988 refused to be
// instrumented from the inside.
extern "C" void gate6_result(u32 index, Context *c, u32 result, u32 arg)
{
    watch_note(c);
    // Remember it, whether or not it failed. RFile::Read hands the file server
    // a buffer and a maximum, and the server writes up to that maximum into
    // this process -- so if the maximum is larger than the cell the buffer came
    // from, the overflow is performed by a server and lands wherever the heap
    // put the next thing. That is the kind of thing that ends kernel-side.
    if (result) {
        const u32 n = c->allocNext & (ALLOC_RING - 1);
        c->allocPtr[n] = result;
        c->allocLen[n] = arg;
        c->allocNext++;
    }
    // RFile::Open is the other way round -- zero is success there -- so it is
    // recorded whatever it says, and the record's existence is the point: it
    // means the call returned at all.
    if (index == IMPORT_FILE_OPEN) {
        log_event(c, NOTE_RESULT_OF, index);
        log_event(c, NOTE_RESULT, result);
        log_block(c);
        return;
    }
    // Only the failures. An allocator that succeeded says nothing worth the
    // time -- and time is what the run is short of -- while a zero is the whole
    // answer to whether the phone is running out of memory.
    if (result)
        return;
    log_event(c, NOTE_RESULT, result);
    log_event(c, NOTE_RESULT_OF, index);
    log_event(c, NOTE_RESULT_ARG, arg);
    log_block(c);
}

// The result goes back over the saved r0 before the registers are restored, so
// the caller still receives it. Every pc-relative offset counts from the
// instruction's own address plus eight, which is where the first attempt at
// this went wrong -- each literal was read one word late.
// trace_thunk with the first argument in place of the return address, and the
// record written before the call rather than after. A call that never returns
// -- an allocation the phone cannot satisfy, say -- leaves nothing behind
// otherwise.
// A TDesC16 keeps its text in a different place for each of the four layouts,
// and the game uses more than one. -> the text, or zero.
static const u16 *des_text(const u32 *d, u32 *length)
{
    if (!d || ((u32)d & 3) || (u32)d < 0x400000 || (u32)d >= 0x10000000)
        return 0;
    *length = d[0] & 0x0FFFFFFF;
    // Measured, not deduced: the names this game hands RFile::Open carry type
    // 4, and the text is where a type-4 word says it is only if the third word
    // is read as a pointer. Reading it as inline text -- which is what the
    // published layout for EBufCPtr would say -- gives rubbish for every name
    // that decoded cleanly before.
    switch (d[0] >> KTypeShift) {
    case EBufC:    return (const u16 *)(d + 1);     // length, then the text
    case EPtrC:    return (const u16 *)d[1];        // length, then a pointer
    case EBufType: return (const u16 *)(d + 2);     // length, max, then the text
    default:       return (const u16 *)d[2];        // length, max, then a pointer
    }
}

extern "C" void gate6_arg(u32 index, Context *c, u32 a0, u32 a1)
{
    watch_note(c);
    log_event(c, NOTE_CALL_ARG, index);
    log_event(c, NOTE_RESULT_ARG, a0);
    log_event(c, NOTE_CALLER, a1);
    // RFile::Open's third argument is the name. Sixteen characters is enough
    // for "cwivenc.dat" and for anything else this game opens.
    if (WATCH_FREES && (index == IMPORT_DELETE_OP || index == IMPORT_VEC_DELETE_OP ||
                        index == IMPORT_USER_FREE_OP)) {
        if (!a0)
            return;
        // The bookkeeping runs on every free from the first one -- a cell has
        // to be marked spent when it is freed or a later double free reads as
        // an ordinary match. Only the *records* are rationed: frees are
        // constant traffic, so the plain ones are kept for the stretch the run
        // dies in, and a double or a stray is reported wherever it happens.
        // The pointer goes down before anything is done with it. The run that
        // got furthest died inside a free, between the record naming the
        // pointer and the record saying what the ring made of it -- and the
        // exact-logging window was at the start of the run, where the failure
        // was wrongly believed to be. A free is rare enough (thirty-one in a
        // run) to afford a write of its own, and it is the one place the
        // record has to survive.
        log_event(c, NOTE_FREE, a0);
        log_block(c);
        const int loud = (c->traceCount >= (u32)FREE_WATCH_FROM);
        for (u32 k = 1; k <= ALLOC_RING; k++) {
            const u32 i = (c->allocNext - k) & (ALLOC_RING - 1);
            if (c->allocPtr[i] != a0)
                continue;
            if (c->allocLen[i] == SPENT) {
                log_event(c, NOTE_FREE_TWICE, a0);
                log_block(c);
            } else {
                // Flushed, like the pointer above it. Round 45 named the
                // pointer it dies on and not what the ring made of it, because
                // a plain match was written and left in the buffer -- the same
                // shape as the five failures before it, where the record was
                // there and never reached the disk.
                if (loud) {
                    log_event(c, NOTE_FREE_OK, c->allocLen[i]);
                    // The cell's own header. RHeap keeps a cell's length in
                    // the word before the payload, and that word is the first
                    // thing User::Free reads -- so it is what faults when a
                    // free faults on a cell everything else says is fine. The
                    // ring vouched for this pointer, so reading behind it is
                    // safe. Two words, because the healthy ones give the
                    // baseline that makes the damaged one obvious.
                    const u32 hdr = ((const u32 *)a0)[-1];
                    log_event(c, NOTE_CELL_HDR, hdr);
                    log_event(c, NOTE_CELL_HDR, ((const u32 *)a0)[-2]);
                    // And the cell after this one. Freeing coalesces: RHeap
                    // reads the neighbour's header to decide whether to merge,
                    // so a free can fault on a header that is not its own.
                    // Everything about this cell has now measured clean, which
                    // leaves the one part of a free that is about somebody
                    // else's memory. The size is known good, so stepping by it
                    // is safe; the bounds check is for the case where it
                    // is not.
                    // Bounded by the highest address any allocation has
                    // reached. The first attempt checked only that the size
                    // looked sane and read the neighbour of the *last* cell
                    // straight off the end of the heap -- the emulator's fault
                    // moved from 0x30002 to 0x9B0000, which is what caught it.
                    // An instrument that walks past the end of the thing it is
                    // measuring is the same mistake as all the others.
                    const u32 *next = (const u32 *)((const u8 *)a0 - 4 + hdr);
                    log_event(c, NOTE_NEXT_HDR, (u32)next);
                    // Vouched the same way this cell was: the ring has to have
                    // been handed a payload one word past it. Nothing else is
                    // safe to dereference -- the first attempt bounded the read
                    // by the highest address any allocation had reached and
                    // still walked off the end, moving the emulator's fault
                    // from 0x30002 to 0x9B0000. (The extra records are not the
                    // perturbation: three events per free with no dereference
                    // leave the emulator at 0x30002.) A neighbour the ring
                    // does not know is reported as a pointer and left alone,
                    // which is itself the answer -- a free cell, or one older
                    // than the ring.
                    for (u32 j = 0; j < ALLOC_RING; j++) {
                        if (c->allocPtr[j] != (u32)next + 4)
                            continue;
                        log_event(c, NOTE_NEXT_HDR, next[0]);
                        log_event(c, NOTE_NEXT_HDR, c->allocLen[j]);
                        break;
                    }
                    log_block(c);
                }
                c->allocLen[i] = SPENT;
            }
            return;
        }
        // Not in the ring at all. Two hundred and fifty-six allocations back is
        // a long way, so this is only worth saying late, where it is a claim
        // about this free rather than about the ring's depth.
        if (loud) {
            log_event(c, NOTE_FREE_STRAY, a0);
            log_block(c);
        }
        return;
    }

    if (index == IMPORT_FILE_OPEN) {
        u32 n = 0;
        const u16 *t = des_text((const u32 *)c->argR2, &n);
        // Into the box, always: it rides the write the box was making anyway,
        // and it turns "it stopped at a read" into "it stopped on this file".
        if (t && n <= 256 && !((u32)t & 1) &&
            (u32)t >= 0x400000 && (u32)t < 0x10000000) {
            const u32 chars = 2 * BOX_NAME_WORDS;
            const u32 from = (n > chars) ? n - chars : 0;
            for (u32 i = 0; i < BOX_NAME_WORDS; i++) {
                const u32 k = from + 2 * i;
                c->boxData[BOX_NAME + i] = (k < n)
                    ? (t[k] | ((k + 1 < n) ? (t[k + 1] << 16) : 0)) : 0;
            }
        }
        if (QUIET)
            return;
        // The layout word, so that a name that comes out shifted says which
        // layout it was read as rather than being guessed at.
        log_event(c, NOTE_RESULT_ARG, c->argR2 ? *(const u32 *)c->argR2 : 0);
        // The tail, because the path is long and the name is at the end of it.
        enum { NAME_CHARS = 24 };
        if (t && n <= 256 && !((u32)t & 1) &&
            (u32)t >= 0x400000 && (u32)t < 0x10000000)
            for (u32 i = ((n > NAME_CHARS) ? n - NAME_CHARS : 0) & ~1u; i < n; i += 2)
                log_event(c, NOTE_TEXT, t[i] | ((i + 1 < n) ? (t[i + 1] << 16) : 0));
        log_block(c);
        return;
    }
    // For RFile::Read the second argument is the descriptor the file server
    // will write into, and what it says about itself is the whole question:
    // type and length in the first word, maximum in the second, and the buffer
    // in the third.
    if (a1 >= 0x400000 && a1 < 0x10000000 && !(a1 & 3)) {
        for (u32 i = 0; i < 3; i++)
            log_event(c, NOTE_R5_AT, ((const u32 *)a1)[i]);
        // And the cell the buffer belongs to, if we saw it allocated: its size
        // against the maximum the server has been given.
        const u32 want = ((const u32 *)a1)[1];
        const u32 buf = ((const u32 *)a1)[2];
        // Newest first. The ring knows nothing about frees, so an address
        // that has been handed out twice appears twice in it, and the entry
        // that describes the cell the buffer is in now is the later one. In
        // slot order the stale one wins, which is how a perfectly ordinary
        // read came to be written up here as a hundred-and-sixty-kilobyte
        // overflow of a thirty-one byte cell.
        for (u32 k = 1; k <= ALLOC_RING; k++) {
            const u32 i = (c->allocNext - k) & (ALLOC_RING - 1);
            if (c->allocPtr[i] && buf >= c->allocPtr[i] &&
                buf < c->allocPtr[i] + c->allocLen[i]) {
                log_event(c, NOTE_CELL_AT, c->allocPtr[i]);
                log_event(c, NOTE_CELL, c->allocLen[i]);
                const u32 room = c->allocLen[i] - (buf - c->allocPtr[i]);
                if (want > room) {
                    // The file server writes up to the maximum it is given, and
                    // it does it from outside this process. Asking it for a
                    // hundred and sixty kilobytes into a thirty-one byte cell
                    // is not a fault here when it goes wrong -- it is a fault
                    // in the server, which is the one kind that takes a phone
                    // down rather than an application. So the maximum is cut
                    // to what the cell can hold. The read comes back short,
                    // which the game may not like; the alternative is a heap
                    // smashed by something that cannot be stopped once asked.
                    log_event(c, NOTE_OVERFLOW, want);
                    if (CLAMP_THE_READS)
                        ((u32 *)a1)[1] = room;
                }
                break;
            }
        }
    }
    log_block(c);
}

enum { ARG_WORDS = 16 };

// Three arguments, not two: r0 and r1 go to the handler in r2 and r3, and r2
// is stored first, before the moves below overwrite it. A fourth would need
// the stack.
//
// The store goes through the field's own address, carried as a literal, and
// not as an offset from the context. `str r2, [r12, #off]` encodes twelve bits
// and the field sat at 9404 once the silent build's log buffer grew in front
// of it, so the offset was truncated and the write went 8192 bytes short --
// into the log buffer, silently, where nothing ever reads it. A literal cannot
// be truncated.
static u32 arg_thunk(u8 *code, Context *ctx, u32 value, u32 target)
{
    u32 *b = (u32 *)code;
    b[0]  = 0xE92D500F;                 // stmdb sp!, {r0-r3, r12, lr}
    b[1]  = 0xE59FC020;                 // ldr   r12, [pc, #32]  -> b[11] &argR2
    b[2]  = 0xE58C2000;                 // str   r2, [r12]  -- the third argument
    // lr, not r1. The second argument of a `delete` is junk (0x6d6a2b7b in
    // every record of round 49) and the question the run is now on is *which*
    // delete this is -- the 99th of a run, in a game with no symbols. This
    // thunk tail-jumps, so lr here is still the game's own return address:
    // the instruction after the call, in the image, at a fixed offset.
    b[3]  = 0xE1A0300E;                 // mov   r3, lr   -- who called
    b[4]  = 0xE1A02000;                 // mov   r2, r0
    b[5]  = 0xE59F0014;                 // ldr   r0, [pc, #20]   -> b[12] which
    b[6]  = 0xE59F1014;                 // ldr   r1, [pc, #20]   -> b[13] context
    b[7]  = 0xE59FC014;                 // ldr   r12, [pc, #20]  -> b[14] handler
    b[8]  = 0xE12FFF3C;                 // blx   r12
    b[9]  = 0xE8BD500F;                 // ldmia sp!, {r0-r3, r12, lr}
    b[10] = 0xE59FF00C;                 // ldr   pc, [pc, #12]   -> b[15] target
    b[11] = (u32)&ctx->argR2;
    b[12] = value;
    b[13] = (u32)ctx;
    b[14] = (u32)&gate6_arg;
    b[15] = target;
    user_imb_range(b, b + ARG_WORDS);
    return (u32)b;
}

static u32 result_thunk(u8 *code, const void *ctx, u32 value, u32 target)
{
    u32 *b = (u32 *)code;
    b[0] = 0xE92D500F;                  // stmdb sp!, {r0-r3, r12, lr}
    b[1] = 0xE59FC024;                  // ldr   r12, [pc, #36]  -> b[12] target
    b[2] = 0xE12FFF3C;                  // blx   r12             -- let it happen
    b[3] = 0xE1A02000;                  // mov   r2, r0          -- the result
    // r0-r3 do not survive a call, so the argument cannot be kept in one of
    // them across it; the copy pushed on the way in is still there.
    b[4] = 0xE59D3000;                  // ldr   r3, [sp]        -- what was asked
    b[5] = 0xE58D2000;                  // str   r2, [sp]        -- the caller's r0
    b[6] = 0xE59F0014;                  // ldr   r0, [pc, #20]   -> b[13] which
    b[7] = 0xE59F1014;                  // ldr   r1, [pc, #20]   -> b[14] context
    b[8] = 0xE59FC014;                  // ldr   r12, [pc, #20]  -> b[15] handler
    b[9] = 0xE12FFF3C;                  // blx   r12
    b[10] = 0xE8BD500F;                 // ldmia sp!, {r0-r3, r12, lr}
    b[11] = 0xE12FFF1E;                 // bx    lr              -- r0 restored
    b[12] = target;
    b[13] = value;
    b[14] = (u32)ctx;
    b[15] = (u32)&gate6_result;
    user_imb_range(b, b + 16);
    return (u32)b;
}

extern "C" void gate6_probe(u32 marker, Context *c, u32 a, u32 b)
{
    // Stations inside a callee are hot: 0xe9988 is called many times before the
    // call that matters, and ten probes through it drowned the run in its own
    // records at 595. So nothing but the first probe reports until the first
    // probe has fired -- that one marks the object, and is the only thing that
    // says the interesting call is the one now running.
    if (marker != (u32)PROBE_FIRST && !c->watchAt)
        return;
    if (marker >= (u32)PROBE_TARGET_FROM && marker < (u32)PROBE_TARGET_TO &&
        a != c->watchAt + 4)
        return;
    if (marker >= (u32)PROBE_QUIET_FROM) {
        const u32 now = ((const u32 *)c->watchAt)[1];
        if (now == c->lastWatch)
            return;
        c->lastWatch = now;
    }
    stack_mark(c);
    c->lastImport = marker;
    const u32 slot = c->traceCount & (BOX_RING - 1);
    c->boxData[4 + slot] = marker;
    c->boxData[BOX_FROM + slot] = a;
    c->traceCount++;
    log_event(c, marker, a);
    log_event(c, NOTE_PROBE_B, b);
    // And the first four words of what a addresses, when it looks like an
    // address this process owns. Half of what a probe is asked is about what
    // is at the pointer, not what the pointer is.
    enum { PROBE_WORDS = LOG_ANYWAY ? 8 : 4 };
    if (a >= 0x400000 && a < 0x10000000 && !(a & 3))
        for (u32 i = 0; i < PROBE_WORDS; i++)
            log_event(c, NOTE_R5_AT, ((const u32 *)a)[i]);
    // The watched word, from the first probe's object, on every probe after
    // it. One record, and it turns a scatter of registers into a timeline of
    // one field.
    if (marker == (u32)PROBE_FIRST && a >= 0x400000 && a < 0x10000000 && !(a & 3)) {
        c->watchAt = a;
        c->lastWatch = ((const u32 *)a)[1];
    }
    watch_note(c);
    // A probe is planted at a site that is about to go wrong, so the block it
    // is in is the one most likely never to be written.
    if (LOG_ANYWAY)
        log_block(c);
}

// The two registers are copied before anything else, because the flag save
// below clobbers r0 -- so ra and rb are the game's own. rb may not be r2 for
// the same reason: r2 is written first.
static void probe_plant(Context *c, u8 *base, const Probe &p, u32 marker)
{
    u32 *site = (u32 *)(base + p.at);
    if (p.rb == 2 || !crumb_safe(*site) || c->spare + PROBE_BYTES > c->spareEnd)
        return;
    u32 *b = (u32 *)c->spare;
    c->spare += PROBE_BYTES;
    b[0]  = 0xE92D500F;                 // stmdb sp!, {r0-r3, r12, lr}
    b[1]  = 0xE1A02000 | p.ra;          // mov   r2, ra
    b[2]  = 0xE1A03000 | p.rb;          // mov   r3, rb
    b[3]  = 0xE10F0000;                 // mrs   r0, cpsr
    b[4]  = 0xE92D0003;                 // stmdb sp!, {r0, r1}
    b[5]  = 0xE59F0020;                 // ldr   r0, [pc, #32]  -> b[15] marker
    b[6]  = 0xE59F1020;                 // ldr   r1, [pc, #32]  -> b[16] context
    b[7]  = 0xE59FC020;                 // ldr   r12, [pc, #32] -> b[17] handler
    b[8]  = 0xE12FFF3C;                 // blx   r12
    b[9]  = 0xE8BD0003;                 // ldmia sp!, {r0, r1}
    b[10] = 0xE128F000;                 // msr   cpsr_f, r0
    b[11] = 0xE8BD500F;                 // ldmia sp!, {r0-r3, r12, lr}
    b[12] = *site;                      // what stood here
    b[13] = 0xE51FF004;                 // ldr   pc, [pc, #-4]
    b[14] = (u32)(site + 1);
    b[15] = marker;
    b[16] = (u32)c;
    b[17] = (u32)&gate6_probe;
    user_imb_range(b, b + 18);
    *site = 0xEA000000 | ((((u32)b - (u32)site - 8) >> 2) & 0x00FFFFFF);
    user_imb_range(site, site + 1);
}

static void crumb_plant_r5(Context *c, u8 *base, u32 at, u32 marker)
{
    u32 *site = 0, original = 0;
    for (u32 i = 0; i < 8; i++) {
        u32 *p = (u32 *)(base + at + 4 * i);
        if (crumb_safe(*p)) { site = p; original = *p; break; }
        if (((*p >> 25) & 7) >= 5) break;
    }
    if (!site || c->spare + CRUMB_BYTES + 8 > c->spareEnd)
        return;
    u32 *b = (u32 *)c->spare;
    c->spare += CRUMB_BYTES + 8;
    b[0] = 0xE92D500F;  b[1] = 0xE10F0000;  b[2] = 0xE92D0003;
    b[3] = 0xE59F0028;  b[4] = 0xE59F1028;  b[5] = 0xE59F2028;
    b[6] = 0xE59FC028;  b[7] = 0xE1A03005;  // mov r3, r5
    b[8] = 0xE12FFF3C;  b[9] = 0xE8BD0003;  b[10] = 0xE128F000;
    b[11] = 0xE8BD500F; b[12] = original;
    b[13] = 0xE51FF004; b[14] = (u32)(site + 1);
    b[15] = marker;     b[16] = (u32)c;
    b[17] = (u32)site - (u32)base;
    b[18] = (u32)&gate6_crumb_r5;
    user_imb_range(b, b + 19);
    *site = 0xEA000000 | ((((u32)b - (u32)site - 8) >> 2) & 0x00FFFFFF);
    user_imb_range(site, site + 1);
}

static void crumb_plant(Context *c, u8 *base, u32 at, u32 marker)
{
    u32 *site = 0;
    u32 original = 0;
    for (u32 i = 0; i < 8; i++) {
        u32 *p = (u32 *)(base + at + 4 * i);
        if (crumb_safe(*p)) { site = p; original = *p; break; }
        if (((*p >> 25) & 7) >= 5) break;       // a branch: go no further
    }
    if (!site || c->spare + CRUMB_BYTES > c->spareEnd)
        return;
    u32 *b = (u32 *)c->spare;
    c->spare += CRUMB_BYTES;
    b[0] = 0xE92D500F;  b[1] = 0xE10F0000;  b[2] = 0xE92D0003;
    b[3] = 0xE59F0024;  b[4] = 0xE59F1024;  b[5] = 0xE59F2024;
    b[6] = 0xE59FC024;  b[7] = 0xE12FFF3C;  b[8] = 0xE8BD0003;
    b[9] = 0xE128F000;  b[10] = 0xE8BD500F; b[11] = original;
    b[12] = 0xE51FF004; b[13] = (u32)(site + 1);
    b[14] = marker;     b[15] = (u32)c;
    b[16] = (u32)site - (u32)base;
    b[17] = (u32)&gate6_crumb;
    user_imb_range(b, b + 18);
    *site = 0xEA000000 | ((((u32)b - (u32)site - 8) >> 2) & 0x00FFFFFF);
    user_imb_range(site, site + 1);
}

extern "C" void gate6_trace(u32 index, Context *c, u32 caller)
{
    watch_note(c);
    stack_mark(c);
    if (TRACE_IMPORTS)
        note(c, index, ' ');
    if (index == IMPORT_LEAVE || index == IMPORT_EXIT) {
        c->reached |= (index == IMPORT_LEAVE) ? REACHED_LEAVE : REACHED_EXIT;
        note(c, caller >> 16, 'R');
        note(c, caller & 0xFFFF, 'r');
        box_flush(c);
    }
    c->lastImport = index;
    const u32 slot = c->traceCount & (BOX_RING - 1);
    c->boxData[4 + slot] = index;
    c->boxData[BOX_FROM + slot] = caller - c->codeBase;
    ++c->traceCount;
    log_event(c, index, caller - c->codeBase);
    // A clock, every sixteenth milestone. Four runs of the fixed build have
    // ended between 110 and 115 milestones, and the one explanation left is
    // that the game simply takes longer than the phone will allow in a single
    // RunL. Ticks say so or they do not: a phone that stops at the same moment
    // each time and a different milestone is a clock, and one that stops at the
    // same milestone after a different time is not.
    if (LOG_THE_CLOCK && (++c->clockTick & 15) == 0)
        log_event(c, NOTE_TICK, user_tickcount());
    vptr_check(c);                  // whichever call it was, it is named above
    // Silent still has to answer "how far", so the box goes down once every
    // thirty-two traced events: four writes on a run of the length the phone
    // manages, against a hundred and twenty-nine last time. It carries the
    // count and the last thirty-two events, which is the yardstick.
    if (SILENT && (c->traceCount & (BOX_EVERY_TRACED - 1)) == 0)
        box_flush(c);
    if (index == IMPORT_LEAVE || index == IMPORT_EXIT)
        log_block(c);               // the tail of the block, on the way out
}

// The framework calling one of our objects. Rare enough to write out every
// time, so the record is exact rather than to the nearest sixteen.
enum { REACHED_SLOT = 16 };

// The app UI's vtable pointer was found overwritten with 1 by the time the
// framework dispatched ProcessCommandParametersL through it. Every import the
// game makes and every call the framework makes into us comes past here, so
// the record names the last one it was still right for.
static void vptr_check(Context *c)
{
    if (c->wrapUi && c->wrapUi[0] != c->wrapUiVptr) {
        log_event(c, NOTE_VPTR, c->wrapUi[0]);
        if (!QUIET) log_block(c);
        c->wrapUiVptr = c->wrapUi[0];   // say it once per change, not per call
    }
}

extern "C" void gate6_slot(u32 code, Context *c, u32)
{
    note(c, code, '+');
    c->lastCall = code;
    c->reached |= REACHED_SLOT;         // so a zero can be told from a silence
    log_event(c, NOTE_SLOT, code);      // the half of the story the log lacked
    vptr_check(c);
    if (BOX_ON_SLOT)
        box_flush(c);
}

// Every slot of a wrapper's vtable, so that whatever the framework does to it
// last is on record. The object is named in the top byte.
enum { OBJ_APP = 1, OBJ_DOC = 2, OBJ_UI = 3, OBJ_CONTROL = 4, OBJ_TIMER = 5 };

static void instrument(Context *c, u32 *vt, int slots, u32 object)
{
    for (int i = 0; i < slots; i++) {
        if (c->spare + TRACE > c->spareEnd)
            return;
        vt[VT_HEADER + i] = trace_thunk(c->spare, c, (object << 8) | (u32)i,
                                        vt[VT_HEADER + i], (u32)&gate6_slot);
        c->spare += TRACE;
    }
}

// There was a timer here that flushed the record every five milliseconds. It
// was written before every import wrote its own record, when the worry was a
// fault arriving long after the last import; it has been redundant since, and
// it was doing two hundred RFile::Flush calls a second to a memory card for as
// long as the game ran. On a host file that costs nothing, which is why the
// emulator never minded. Every one of those flushes commits to the card on a
// phone, and the reboots -- hardware only, asynchronous, no panic, no leave,
// always at about the same point because the game takes about the same time to
// get there -- fit that and nothing in the game's own code.
static void box_start(Context *) {}

// ---- the timer -------------------------------------------------------------

typedef void *(*TimerCtor)(void *self, int priority);

// Which of the ways back into the game have been taken. A phone can report one
// number and only once, so the ones that must not stop are recorded and the one
// under test carries the record out with it.
enum { REACHED_ABORT = 1, REACHED_RESTART = 2, REACHED_DOCANCEL = 4, REACHED_RUNERROR = 8 };
enum { REACHED_RUNL = 32 };   // the frame loop ran at least once

extern "C" void gate6_timer_docancel(void *, u32, Context *c)
{
    c->reached |= REACHED_DOCANCEL;
    old_call(c->oldTimer, OLD_DOCANCEL);
}

// Left on. Releasing the screen is not a one-line switch: the graphics context
// only exists once StartL has run, so without it the run dies writing through
// a null at three milestones. If the window server's abort timeout turns out
// to be the reboot, this needs the context standing in as well.
enum { HOLD_THE_SCREEN = 1, RELEASE_THE_SCREEN = 1 };

static void dsa_refresh(Context *c);

extern "C" void gate6_timer_runl(void *, u32, Context *c)
{
    c->reached |= REACHED_RUNL;
    c->frames++;

    // The request completed into the wrapper, and the game reads the result out
    // of its own object, so carry it across before handing over.
    c->oldTimer[ACTIVE_STATUS / 4] = c->wrapTimer[ACTIVE_STATUS / 4];
    c->oldTimer[ACTIVE_ACTIVE / 4] = c->wrapTimer[ACTIVE_ACTIVE / 4];

    // The frame the game is about to draw reads the direct screen access
    // object, so its view of it is brought up to date first.
    dsa_refresh(c);

    old_call(c->oldTimer, OLD_RUNL);
}

extern "C" u32 gate6_timer_runerror(void *, u32 error, Context *c)
{
    c->reached |= REACHED_RUNERROR;
    return old_call1(c->oldTimer, OLD_RUNERROR, error);
}

extern "C" void gate6_request_complete(u32 **status, int reason, Context *c)
{
    typedef void (*RequestComplete)(u32 **, int);
    if (c->oldTimer && c->wrapTimer &&
        *status == (u32 *)((u8 *)c->oldTimer + ACTIVE_STATUS))
        *status = (u32 *)((u8 *)c->wrapTimer + ACTIVE_STATUS);
    ((RequestComplete)c->newRequestComplete)(status, reason);
}

// The game constructs its CTimer; ours is constructed alongside it, and from
// here on everything the game does to its own goes to ours instead. A GCC98r2
// constructor returns the object, which is still the game's.
extern "C" void *gate6_ctimer_ctor(u32 *oldSelf, int priority, Context *c)
{
    c->oldTimer = oldSelf;

    u32 *t = (u32 *)user_allocz(WRAP_BYTES);
    if (!t) PANIC(CAT_MEM, -35);
    ((TimerCtor)c->newTimerCtor)(t, priority);

    u32 *vt = copy_vtable(vtable_of(t), TIMER_SLOTS);
    vt[VT_HEADER + NEW_DOCANCEL] = c->timerThunks[0];
    vt[VT_HEADER + NEW_RUNL] = c->timerThunks[1];
    vt[VT_HEADER + NEW_RUNERROR] = c->timerThunks[2];
    instrument(c, vt, TIMER_SLOTS, OBJ_TIMER);
    t[0] = (u32)(vt + VT_HEADER);

    c->wrapTimer = t;
    return oldSelf;
}

