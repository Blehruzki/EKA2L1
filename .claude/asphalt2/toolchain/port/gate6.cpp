// A wrapper's vtable is a copy of a real one, as many slots long as the class
// was measured to have. The framework is under no obligation to agree: ask it
// for a slot past the end and it reads whatever the heap put after the cell and
// branches there, which is a wild jump that depends on the allocation history
// and so happens on one run and not the next. The copy is padded, and the
// padding answers.
// A wrapper's vtable is a copy of a real one, as many slots long as the class
// was measured to have, and the copy is exactly that big. Padding it looked
// like cheap insurance against the framework asking for a slot past the end --
// and it broke the emulator outright, at the first app slot of the cascade
// after PushContextL, three runs out of three. Not because of the padding: an
// allocation of 384 bytes made at load time and never touched does the same
// thing, while 96 and 2048 leave the run alone. Something here depends on
// where the heap puts things, which is the one explanation that fits a phone
// running the same build twice and only sometimes getting through. Both knobs
// are the bench for finding it and are zero in a real build.
enum { VT_MARGIN = 0 };
enum { HEAP_NUDGE = 0 };

extern "C" u32 gate6_vt_beyond(void) { return 0; }

static u32 *copy_vtable(const u32 *real, int slots)
{
    u32 *vt = (u32 *)user_allocz((VT_HEADER + slots + VT_MARGIN) * 4);
    if (!vt) PANIC(CAT_MEM, -30);
    for (int i = 0; i < VT_HEADER + slots; i++)
        vt[i] = real[i];
    for (int i = 0; i < VT_MARGIN; i++)
        vt[VT_HEADER + slots + i] = (u32)&gate6_vt_beyond;
    return vt;
}

// The other direction. When the game calls a framework method on itself, the
// 9.x implementation must not see the old object, so the call is diverted to
// one of ours -- which needs the context, and gets it in r2:
//
//   ldr r2, [pc, #4]    @ the context, baked in when the stub is built
//   ldr pc, [pc, #4]    @ and on to our implementation
//   .word context
//   .word our function
//
// r0 and r1 pass through untouched, so the old arguments arrive as they were.
static u32 ctx_thunk(u8 *code, const void *ctx, u32 target)
{
    u32 *b = (u32 *)code;
    b[0] = 0xE59F2004;                  // ldr r2, [pc, #4]
    b[1] = 0xE59FF004;                  // ldr pc, [pc, #4]
    b[3] = (u32)ctx;
    b[4] = target;
    user_imb_range(b, b + 5);
    return (u32)b;
}

// The same, for a call that already uses r0 to r2.
//
//   ldr r3, [pc, #4]
//   ldr pc, [pc, #4]
static u32 ctx3_thunk(u8 *code, const void *ctx, u32 target)
{
    u32 *b = (u32 *)code;
    b[0] = 0xE59F3004;
    b[1] = 0xE59FF004;
    b[3] = (u32)ctx;
    b[4] = target;
    user_imb_range(b, b + 5);
    return (u32)b;
}

// The simpler diversion: the 9.x implementation is the right one, it just must
// not be handed the old object. The wrapper does not exist when the stub is
// built, so the thunk reads it from the context each time:
//
//   ldr rN, [pc, #8]    @ rN = the cell holding the wrapper
//   ldr rN, [rN]
//   ldr pc, [pc, #4]
//   .word cell
//   .word the 9.x function
static u32 this_thunk(u8 *code, const void *cell, u32 target, int reg)
{
    u32 *b = (u32 *)code;
    b[0] = 0xE59F0008 | ((u32)reg << 12);           // ldr rN, [pc, #8]
    b[1] = 0xE5900000 | ((u32)reg << 16) | ((u32)reg << 12);
    b[2] = 0xE59FF004;                              // ldr pc, [pc, #4]
    b[4] = (u32)cell;
    b[5] = target;
    user_imb_range(b, b + 6);
    return (u32)b;
}

// A phone reports a fault as KERN-EXEC 3 and nothing else -- no address, no
// instruction. So every import the game makes goes through this first, which
// records which one it was and jumps on. r0 and r12 are saved across the
// record; lr is the caller's and is never touched, and neither are the flags.
//
//   stmdb sp!, {r0, r12}
//   ldr   r0, [pc, #12]     @ where to record it
//   ldr   r12, [pc, #12]    @ which import
//   str   r12, [r0]
//   ldmia sp!, {r0, r12}
//   ldr   pc, [pc, #4]      @ and on to whatever answers it
enum { TRACE = 48 };

// One line of the watched field, from wherever it is called. The field lives
// at a fixed address in the game's memory once the first probe has named it,
// and every wrapper we already own is a station -- no game byte is patched to
// get one, which is the point after 0xe9988 refused to be instrumented from
// the inside: a single probe planted at its third instruction took the run
// from 1240 records to 553.
static void log_event(Context *c, u32 code, u32 from);
static void watch_note(Context *c)
{
    // Four words, not one. A deliberate store into this->[4] touches that word
    // and nothing else; a stray write -- an overrun from the cell before it,
    // or a copy that ran long -- takes its neighbours with it. One record
    // each, and the difference between those two explanations is the whole
    // question now.
    if (!c->watchAt)
        return;
    const u32 *o = (const u32 *)c->watchAt;
    for (u32 i = 0; i < 4; i++)
        log_event(c, NOTE_WATCH, o[i]);
    // And, when the field still looks like an address, the word 0x139588 will
    // read out of it. That instruction -- `ldr r2, [r1, #0x240]` -- is the one
    // the run dies on, so whether the *pre-call* value survives it is the
    // question of whether the call should have written the field at all.
    // Guarded, because the poisoned value must not be dereferenced: that is
    // the fault we are studying, not one to reproduce.
    const u32 v = o[1];
    if (v >= 0x400000 && v < 0x10000000 && !(v & 3))
        log_event(c, NOTE_WATCH_AT240, ((const u32 *)(v + 0x240))[0]);
}

