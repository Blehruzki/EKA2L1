static u32 load_and_start()
{
    u32 fs[2] = { 0, 0 };
    u32 file[4] = { 0, 0, 0, 0 };
    i32 err = fs_connect(fs, -1);
    if (err) PANIC(CAT_FS, err);

    const u16 *paths[3] = { kPath0, kPath1, kPath2 };
    const int lens[3] = { sizeof kPath0 / 2, sizeof kPath1 / 2, sizeof kPath2 / 2 };
    err = -1;
    int chosen = 0;
    for (int i = 0; i < 3 && err; i++) {
        Ptrc16 name;
        name.lengthAndType = ((u32)EPtrC << KTypeShift) | (u32)lens[i];
        name.text = paths[i];
        err = file_open(file, fs, &name, 1);       // EFileRead | EFileShareReadersOnly
        chosen = i;
    }
    if (err) PANIC(CAT_FS, err);

    int size = 0;
    err = file_size(file, &size);
    if (err) PANIC(CAT_FS, err);

    u8 *raw = (u8 *)user_alloc(size);
    if (!raw) PANIC(CAT_MEM, size);

    // RFile::Read stops at the descriptor's maximum, so loop until it is full.
    int got = 0;
    while (got < size) {
        Ptr8 des;
        des.lengthAndType = (u32)EPtr << KTypeShift;
        des.maxLength = size - got;
        des.ptr = raw + got;
        err = file_read(file, &des);
        if (err) PANIC(CAT_FS, err);
        int n = (int)(des.lengthAndType & 0x0FFFFFFF);
        if (n <= 0) break;
        got += n;
    }
    if (got != size) PANIC(CAT_FS, got);

    const E32 *h = (const E32 *)raw;
    if (h->sig != 0x434F5045) PANIC(CAT_HDR, 1);            // 'EPOC'
    if (h->uid1 != 0x10000079) PANIC(CAT_HDR, 2);           // a polymorphic DLL
    if (h->cpu != 0x2000 && h->cpu != 0x1000) PANIC(CAT_HDR, 3);  // must be EKA1
    if (h->compression) PANIC(CAT_HDR, 4);
    if (h->textSize > h->codeSize) PANIC(CAT_HDR, 5);

    const u32 nImports = (h->codeSize - h->textSize) / 4;
    const u32 stubBytes = nImports * SLOT;
    const u32 traceBytes = nImports * TRACE + TRACE;    // one spare for the handler
    const u32 chunkSize = h->codeSize + stubBytes + traceBytes;

    u32 chunk[2] = { 0, 0 };
    err = chunk_createlocalcode(chunk, (int)chunkSize, (int)chunkSize, 0);
    if (err) PANIC(CAT_MEM, err);
    u8 *base = chunk_base(chunk);
    if (!base) PANIC(CAT_MEM, 0x0BADBA5E);

    for (u32 i = 0; i < h->codeSize; i++)
        base[i] = raw[h->codeOffset + i];

    // Rebase. Type 3 is KInferredRelocType and this image has no data section,
    // so every relocation lands in the code we just copied.
    const u32 delta = (u32)base - h->codeBase;
    u32 relocated = 0;
    if (h->codeRelocOffset) {
        const u8 *sec = raw + h->codeRelocOffset;
        const u32 secSize = *(const u32 *)sec;
        u32 o = 8;
        while (o < secSize + 8) {
            const u32 pageBase = *(const u32 *)(sec + o);
            const u32 blockSize = *(const u32 *)(sec + o + 4);
            if (blockSize < 8 || (blockSize & 1)) break;
            for (u32 k = 0; k < (blockSize - 8) / 2; k++) {
                const u16 e = *(const u16 *)(sec + o + 8 + 2 * k);
                if (!e) continue;
                const u32 at = pageBase + (e & 0x0FFF);
                if (at + 4 > h->codeSize) PANIC(CAT_HDR, 6);
                *(u32 *)(base + at) += delta;
                relocated++;
            }
            o += blockSize;
        }
    }
    if (!relocated) PANIC(CAT_HDR, 7);

    // Load the 9.x libraries the forwarding table names. Resolving at run time
    // rather than through our own import section means an ordinal this phone
    // does not have is a null we can count, not a refusal to start at all.
    u32 libs[24];
    if (kShimDllCount > 24) PANIC(CAT_SHIM, (int)kShimDllCount);
    Ptrc16 nopath;
    nopath.lengthAndType = (u32)EPtrC << KTypeShift;
    nopath.text = 0;
    for (u32 i = 0; i < kShimDllCount; i++) {
        libs[i] = 0;
        Ptrc16 nm;
        nm.lengthAndType = ((u32)EPtrC << KTypeShift) | (u32)kShimDllLen[i];
        nm.text = kShimDllName[i];
        err = rlibrary_load(&libs[i], &nm, &nopath);
        if (err) PANIC(CAT_LIB, (int)(i * 1000) + err);
    }

    // Build one stub per import and write its address into the import address
    // table, which on EKA1 sits at the end of the code section.
    //   ldr r0, [pc, #0]   -> the report code
    //   ldr pc, [pc, #0]   -> gate6_report
    u32 *iat = (u32 *)(base + h->textSize);
    u8 *stub = base + h->codeSize;
    u8 *trace = stub + stubBytes;
    u32 forwarded = 0, missing = 0;

    Context *ctx = (Context *)user_allocz((int)sizeof(Context));
    if (!ctx) PANIC(CAT_MEM, -23);
    ctx->path = paths[chosen];
    ctx->pathLen = lens[chosen];
    ctx->lastImport = 0xFFFF;               // nothing yet

    // The handler takes a TExcType in r0 and has nowhere to keep the context,
    // so it arrives through a thunk of its own.
    {
        u32 *b = (u32 *)(trace + nImports * TRACE);
        b[0] = 0xE1A01000;                  // mov r1, r0   -- the exception type
        b[1] = 0xE59F0000;                  // ldr r0, [pc, #0]
        b[2] = 0xE59FF000;                  // ldr pc, [pc, #0]
        b[3] = (u32)ctx;
        b[4] = (u32)&gate6_fault;
        user_setexceptionhandler(b, 0xFFFFFFFF);
    }
    for (u32 i = 0; i < nImports; i++) {
        u32 *s = (u32 *)(stub + SLOT * i);
        s[0] = 0xE59F0000;                  // ldr r0, [pc, #0]  -> the report code
        s[1] = 0xE59FF000;                  // ldr pc, [pc, #0]  -> gate6_report
        s[2] = nImports * 1000 + i;
        s[3] = (u32)&gate6_report;
        iat[i] = (u32)s;

        const u32 entry = (i < kShimCount) ? kShimTable[i] : 0;
        const u32 kind = entry >> 24;
        if (!kind)
            continue;

        if (kind == KIND_LOCAL) {
            switch (entry & 0xFFFF) {
            case LOCAL_NEGSF2:
                s[0] = 0xE2200102;          // eor r0, r0, #0x80000000
                s[1] = 0xE12FFF1E;          // bx  lr
                break;
            case LOCAL_NOOP:                // an empty body: _Reserved slots, CBase
                s[0] = 0xE3A00000;          // mov r0, #0
                s[1] = 0xE12FFF1E;          // bx  lr
                break;
            case LOCAL_TRAP_ENTER:          // TTrap::Trap(TInt&): first pass, no error
                s[0] = 0xE3A00000;          // mov r0, #0
                s[1] = 0xE5810000;          // str r0, [r1]
                s[2] = 0xE12FFF1E;          // bx  lr
                break;
            case LOCAL_TINT64_SET:          // TInt64 from a TInt: sign-extend
                s[0] = 0xE5801000;          // str r1, [r0]
                s[1] = 0xE1A02FC1;          // mov r2, r1, asr #31
                s[2] = 0xE5802004;          // str r2, [r0, #4]
                s[3] = 0xE12FFF1E;          // bx  lr     -- r0 is still the object
                break;
            case LOCAL_MEM_COMPARE:
                s[0] = 0xE51FF004;          // ldr pc, [pc, #-4]
                s[1] = (u32)&gate6_mem_compare;
                break;
            default:
                s[0] = 0xE51FF004;
                s[1] = (u32)&gate6_pure_virtual;
                break;
            }
            forwarded++;
            continue;
        }

        void *fn = rlibrary_lookup(&libs[(entry >> 16) & 0xFF], (int)(entry & 0xFFFF));
        if (!fn) {
            missing++;                      // the stub stays, so we hear about it
            continue;
        }
        if (kind == KIND_CALL) {
            iat[i] = (u32)fn;
        } else if (kind == KIND_SRET8) {
            // GCC98r2 returned an eight-byte structure in r0 and r1; EABI wants
            // a buffer in r0 and pushes `this` to r1. Borrow eight bytes of
            // stack, let the callee fill them, and hand them back in registers.
            s[0] = 0xE92D4010;              // push  {r4, lr}
            s[1] = 0xE24DD008;              // sub   sp, sp, #8
            s[2] = 0xE1A01000;              // mov   r1, r0      -- `this`
            s[3] = 0xE1A0000D;              // mov   r0, sp      -- the buffer
            s[4] = 0xE59F4008;              // ldr   r4, [pc, #8]
            s[5] = 0xE12FFF34;              // blx   r4
            s[6] = 0xE8BD0003;              // ldmia sp!, {r0, r1}
            s[7] = 0xE8BD8010;              // pop   {r4, pc}
            s[8] = (u32)fn;
        } else if (kind == KIND_ARG3) {
            s[0] = 0xE3A02000;              // mov r2, #0    -- the added argument
            s[1] = 0xE51FF004;              // ldr pc, [pc, #-4]
            s[2] = (u32)fn;
        } else {
            s[0] = 0xE92D4000;              // push {lr}
            s[1] = 0xE59FC008;              // ldr  r12, [pc, #8]
            s[2] = 0xE12FFF3C;              // blx  r12
            s[3] = 0xE1A00001;              // mov  r0, r1   -- the remainder
            s[4] = 0xE8BD8000;              // pop  {pc}
            s[5] = (u32)fn;
        }
        forwarded++;
    }
    if (!forwarded) PANIC(CAT_SHIM, (int)missing);

    // The stub slot of a resolved import is spare -- its address went straight
    // into the table -- so the diversions are built there.
    if (nImports <= IMPORT_BASECONSTRUCTL) PANIC(CAT_SHIM, (int)nImports);
    iat[IMPORT_BASECONSTRUCTL] = ctx_thunk(stub + SLOT * IMPORT_BASECONSTRUCTL,
                                           ctx, (u32)&gate6_baseconstructl);

    if (nImports > IMPORT_CREATEWINDOWL)
        iat[IMPORT_CREATEWINDOWL] = ctx_thunk(stub + SLOT * IMPORT_CREATEWINDOWL,
                                              ctx, (u32)&gate6_create_window);
    if (nImports > IMPORT_DLL_NAME)
        iat[IMPORT_DLL_NAME] = ctx_thunk(stub + SLOT * IMPORT_DLL_NAME,
                                         ctx, (u32)&gate6_dll_name);
    if (nImports > IMPORT_COEENV_STATIC)
        iat[IMPORT_COEENV_STATIC] = (u32)&gate6_coeenv_static;
    if (nImports > IMPORT_COECONTROL_CTOR)
        iat[IMPORT_COECONTROL_CTOR] = (u32)&gate6_coecontrol_ctor;
    if (nImports > IMPORT_WINDOW) {
        u32 *w = (u32 *)(stub + SLOT * IMPORT_WINDOW);
        w[0] = 0xE5900000 | OLD_CONTROL_WIN;    // ldr r0, [r0, #0x20]  -- iWin
        w[1] = 0xE12FFF1E;                      // bx  lr
        iat[IMPORT_WINDOW] = (u32)w;
    }
    if (nImports > IMPORT_ADDTOSTACKL && IMPORT_ADDTOSTACKL < kShimCount &&
        (kShimTable[IMPORT_ADDTOSTACKL] >> 24) == KIND_CALL)
        iat[IMPORT_ADDTOSTACKL] = pair_thunk(stub + SLOT * IMPORT_ADDTOSTACKL,
                                             &ctx->wrapUi, &ctx->wrapControl,
                                             iat[IMPORT_ADDTOSTACKL]);

    for (u32 k = 0; k < sizeof kDiverts / sizeof kDiverts[0]; k++) {
        const u32 j = kDiverts[k].import;
        // An import the shim could not answer keeps its reporting stub: sending
        // it through a diversion would lose the one thing it can still tell us.
        if (j >= nImports || j >= kShimCount || (kShimTable[j] >> 24) != KIND_CALL)
            continue;
        u32 **cell = (kDiverts[k].object == ON_CONTROL) ? &ctx->wrapControl : &ctx->wrapUi;
        iat[j] = this_thunk(stub + SLOT * j, cell, iat[j], kDiverts[k].arg);
    }

    // Last, so that it records every import however it ended up being answered.
    for (u32 i = 0; i < nImports; i++)
        iat[i] = trace_thunk(trace + TRACE * i, &ctx->lastImport, i, iat[i]);

    // Enter it. EKA1 calls a DLL's entry point with EDllProcessAttach first,
    // then apparc asks ordinal 1 for the application object.
    typedef int (*EntryFn)(int);
    typedef void *(*Ordinal1Fn)(void);
    ((EntryFn)(base + h->entryPoint))(0);
    const u32 ord1 = *(const u32 *)(raw + h->exportDirOffset);
    void *app = ((Ordinal1Fn)(base + ord1))();
    if (!app) PANIC(CAT_NUL, (int)(forwarded * 1000 + missing));
    // The 9.x application: built the ordinary way, then told which old object
    // it stands for, with its two overridden slots pointed at the game.
    u32 *wrap = (u32 *)user_allocz(WRAP_BYTES);
    if (!wrap) PANIC(CAT_MEM, -20);
    eikapplication_ctor(wrap);
    wrap[WRAP_OLD] = (u32)app;
    wrap[WRAP_CTX] = (u32)ctx;

    u32 *vt = copy_vtable(vtable_of(wrap), APP_SLOTS);
    vt[VT_HEADER + SLOT_APP_DLL_UID] = (u32)&gate6_app_dll_uid;
    vt[VT_HEADER + SLOT_CREATE_DOCUMENT] = (u32)&gate6_create_document;
    wrap[0] = (u32)(vt + VT_HEADER);
    return (u32)wrap;

}
