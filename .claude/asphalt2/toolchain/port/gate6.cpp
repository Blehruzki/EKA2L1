enum { WRAP_BYTES = 2048, WRAP_OLD = WRAP_BYTES / 4 - 1, WRAP_CTX = WRAP_BYTES / 4 - 2 };

// What the shim needs to know and cannot keep in a global. Every wrapper holds
// a pointer to it, so any of them can find it from `this`.
struct Context {
    u32 *wrapUi;
    u32 *wrapControl;
    const u16 *path;        // where the game was loaded from
    int pathLen;
    u32 lastImport;         // the last import the game called: see the tracer
};

static Context *context_of(const void *wrapper)
{
    return (Context *)((const u32 *)wrapper)[WRAP_CTX];
}

static const u32 *vtable_of(const u32 *object)
{
    return (const u32 *)object[0] - VT_HEADER;
}

static u32 *copy_vtable(const u32 *real, int slots)
{
    u32 *vt = (u32 *)user_allocz((VT_HEADER + slots) * 4);
    if (!vt) PANIC(CAT_MEM, -30);
    for (int i = 0; i < VT_HEADER + slots; i++)
        vt[i] = real[i];
    return vt;
}

// The other direction. When the game calls a framework method on itself, the
// 9.x implementation must not see the old object, so the call is diverted to
// one of ours -- which needs the context, and gets it in r2:
//
//   ldr r2, [pc, #4]    @ the context, baked in when the stub is built
//   ldr pc, [pc, #4]    @ and on to our implementation
//   .word context
//   .word our function
//
// r0 and r1 pass through untouched, so the old arguments arrive as they were.
static u32 ctx_thunk(u8 *code, const void *ctx, u32 target)
{
    u32 *b = (u32 *)code;
    b[0] = 0xE59F2004;                  // ldr r2, [pc, #4]
    b[1] = 0xE59FF004;                  // ldr pc, [pc, #4]
    b[3] = (u32)ctx;
    b[4] = target;
    return (u32)b;
}

// The simpler diversion: the 9.x implementation is the right one, it just must
// not be handed the old object. The wrapper does not exist when the stub is
// built, so the thunk reads it from the context each time:
//
//   ldr rN, [pc, #8]    @ rN = the cell holding the wrapper
//   ldr rN, [rN]
//   ldr pc, [pc, #4]
//   .word cell
//   .word the 9.x function
static u32 this_thunk(u8 *code, const void *cell, u32 target, int reg)
{
    u32 *b = (u32 *)code;
    b[0] = 0xE59F0008 | ((u32)reg << 12);           // ldr rN, [pc, #8]
    b[1] = 0xE5900000 | ((u32)reg << 16) | ((u32)reg << 12);
    b[2] = 0xE59FF004;                              // ldr pc, [pc, #4]
    b[4] = (u32)cell;
    b[5] = target;
    return (u32)b;
}

// A phone reports a fault as KERN-EXEC 3 and nothing else -- no address, no
// instruction. So every import the game makes goes through this first, which
// records which one it was and jumps on. r0 and r12 are saved across the
// record; lr is the caller's and is never touched, and neither are the flags.
//
//   stmdb sp!, {r0, r12}
//   ldr   r0, [pc, #12]     @ where to record it
//   ldr   r12, [pc, #12]    @ which import
//   str   r12, [r0]
//   ldmia sp!, {r0, r12}
//   ldr   pc, [pc, #4]      @ and on to whatever answers it
enum { TRACE = 48 };

static u32 trace_thunk(u8 *code, const void *cell, u32 index, u32 target)
{
    u32 *b = (u32 *)code;
    b[0] = 0xE92D1001;
    b[1] = 0xE59F000C;
    b[2] = 0xE59FC00C;
    b[3] = 0xE580C000;
    b[4] = 0xE8BD1001;
    b[5] = 0xE59FF004;
    b[6] = (u32)cell;
    b[7] = index;
    b[8] = target;
    return (u32)b;
}

// Then a fault says where it happened, in the only terms the phone gives us.
extern "C" void gate6_fault(Context *c, int type)
{
    PANIC(CAT_FLT, (int)(c->lastImport * 100 + (u32)(type & 63)));
}

// Both at once, for a call that is given one wrapper and made on another. Five
// instructions and three words is exactly the slot, with nothing to spare.
static u32 pair_thunk(u8 *code, const void *cell0, const void *cell1, u32 target)
{
    u32 *b = (u32 *)code;
    b[0] = 0xE59F000C;                  // ldr r0, [pc, #12]
    b[1] = 0xE5900000;                  // ldr r0, [r0]
    b[2] = 0xE59F1008;                  // ldr r1, [pc, #8]
    b[3] = 0xE5911000;                  // ldr r1, [r1]
    b[4] = 0xE59FF004;                  // ldr pc, [pc, #4]
    b[5] = (u32)cell0;
    b[6] = (u32)cell1;
    b[7] = target;
    return (u32)b;
}

