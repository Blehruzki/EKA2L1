extern "C" u32 gate6_main()
{
    // Before anything can leave. The object has to outlive the thread's work,
    // so it goes on the heap rather than this frame; the constructor writes
    // only its own fields, so the room is generous on purpose.
    void *globals = user_allocz(512);
    if (!globals) PANIC(CAT_MEM, -40);
    cpprt_globals_ctor(globals);

    eikstart_runapplication(0, (u32)&gate6_new_application, 0, 0);
    PANIC(CAT_RET, 0);
    return 0;
}

static u32 load_and_start()
{
    u32 fs[2] = { 0, 0 };
    u32 file[4] = { 0, 0, 0, 0 };
    i32 err = fs_connect(fs, -1);
    if (err) PANIC(CAT_FS, err);

    // Where the game came from is not only how it is read: it is the answer to
    // CApaApplication::DllName(), and the game builds the names of its own
    // files beside it -- 6rbc.cwa among them, which lives where an N-Gage card
    // puts it. So the card's own layout is tried first, and the loose copies
    // only after.
    const u16 *paths[3] = { kPath2, kPath0, kPath1 };
    const int lens[3] = { sizeof kPath2 / 2, sizeof kPath0 / 2, sizeof kPath1 / 2 };
    // The game opens eight files of its own beside wherever it was loaded
    // from -- 6rbc.cwa, 6RBC.dat, cis.dat, cwivenc.dat and the rest -- and a
    // missing one is not an error it survives. So a candidate only counts if
    // its directory holds 6rbc.cwa too, and only if none of them does is the
    // first readable .app taken anyway, so the failure is the game's own.
    u16 sibling[32];
    err = -1;
    int chosen = -1;
    int fallback = -1;
    for (int pass = 0; pass < 2 && chosen < 0; pass++) {
        for (int i = 0; i < 3; i++) {
            Ptrc16 name;
            name.lengthAndType = ((u32)EPtrC << KTypeShift) | (u32)lens[i];
            name.text = paths[i];
            if (pass == 0) {
                // The same path with "app" turned into "cwa".
                if (lens[i] > 32) continue;
                for (int k = 0; k < lens[i]; k++) sibling[k] = paths[i][k];
                sibling[lens[i] - 3] = 'c';
                sibling[lens[i] - 2] = 'w';
                sibling[lens[i] - 1] = 'a';
                Ptrc16 with;
                with.lengthAndType = ((u32)EPtrC << KTypeShift) | (u32)lens[i];
                with.text = sibling;
                u32 probe[4] = { 0, 0, 0, 0 };
                if (file_open(probe, fs, &with, 1) != 0) continue;
                rhandle_close(probe);
            }
            err = file_open(file, fs, &name, 1);   // EFileRead | EFileShareReadersOnly
            if (!err) { chosen = i; break; }
            if (fallback < 0) fallback = i;
        }
    }
    if (chosen < 0) {
        if (fallback < 0) PANIC(CAT_FS, err);
        chosen = fallback;
        Ptrc16 name;
        name.lengthAndType = ((u32)EPtrC << KTypeShift) | (u32)lens[chosen];
        name.text = paths[chosen];
        err = file_open(file, fs, &name, 1);
        if (err) PANIC(CAT_FS, err);
    }

    int size = 0;
    err = file_size(file, &size);
    if (err) PANIC(CAT_FS, err);

    u8 *raw = (u8 *)user_alloc(size);
    if (!raw) PANIC(CAT_MEM, size);

    // RFile::Read stops at the descriptor's maximum, so loop until it is full.
    int got = 0;
    while (got < size) {
        Ptr8 des;
        des.lengthAndType = (u32)EPtr << KTypeShift;
        des.maxLength = size - got;
        des.ptr = raw + got;
        err = file_read(file, &des);
        if (err) PANIC(CAT_FS, err);
        int n = (int)(des.lengthAndType & 0x0FFFFFFF);
        if (n <= 0) break;
        got += n;
    }
    if (got != size) PANIC(CAT_FS, got);

    const E32 *h = (const E32 *)raw;
    if (h->sig != 0x434F5045) PANIC(CAT_HDR, 1);            // 'EPOC'
    if (h->uid1 != 0x10000079) PANIC(CAT_HDR, 2);           // a polymorphic DLL
    if (h->cpu != 0x2000 && h->cpu != 0x1000) PANIC(CAT_HDR, 3);  // must be EKA1
    if (h->compression) PANIC(CAT_HDR, 4);
    if (h->textSize > h->codeSize) PANIC(CAT_HDR, 5);

    const u32 nImports = (h->codeSize - h->textSize) / 4;
    const u32 stubBytes = nImports * SLOT;
    const u32 traceBytes = nImports * TRACE + 240 * TRACE;  // spares for our own thunks
    const u32 chunkSize = h->codeSize + stubBytes + traceBytes;

    u32 chunk[2] = { 0, 0 };
    err = chunk_createlocalcode(chunk, (int)chunkSize, (int)chunkSize, 0);
    if (err) PANIC(CAT_MEM, err);
    u8 *base = chunk_base(chunk);
    if (!base) PANIC(CAT_MEM, 0x0BADBA5E);

    for (u32 i = 0; i < h->codeSize; i++)
        base[i] = raw[h->codeOffset + i];

    // Rebase. Type 3 is KInferredRelocType and this image has no data section,
    // so every relocation lands in the code we just copied.
    const u32 delta = (u32)base - h->codeBase;
    u32 relocated = 0;
    if (h->codeRelocOffset) {
        const u8 *sec = raw + h->codeRelocOffset;
        const u32 secSize = *(const u32 *)sec;
        u32 o = 8;
        while (o < secSize + 8) {
            const u32 pageBase = *(const u32 *)(sec + o);
            const u32 blockSize = *(const u32 *)(sec + o + 4);
            if (blockSize < 8 || (blockSize & 1)) break;
            for (u32 k = 0; k < (blockSize - 8) / 2; k++) {
                const u16 e = *(const u16 *)(sec + o + 8 + 2 * k);
                if (!e) continue;
                const u32 at = pageBase + (e & 0x0FFF);
                if (at + 4 > h->codeSize) PANIC(CAT_HDR, 6);
                *(u32 *)(base + at) += delta;
                relocated++;
            }
            o += blockSize;
        }
    }
    if (!relocated) PANIC(CAT_HDR, 7);


    // Load the 9.x libraries the forwarding table names. Resolving at run time
    // rather than through our own import section means an ordinal this phone
    // does not have is a null we can count, not a refusal to start at all.
    u32 libs[24];
    if (kShimDllCount > 24) PANIC(CAT_SHIM, (int)kShimDllCount);
    Ptrc16 nopath;
    nopath.lengthAndType = (u32)EPtrC << KTypeShift;
    nopath.text = 0;
    for (u32 i = 0; i < kShimDllCount; i++) {
        libs[i] = 0;
        Ptrc16 nm;
        nm.lengthAndType = ((u32)EPtrC << KTypeShift) | (u32)kShimDllLen[i];
        nm.text = kShimDllName[i];
        err = rlibrary_load(&libs[i], &nm, &nopath);
        if (err) PANIC(CAT_LIB, (int)(i * 1000) + err);
    }

    // Build one stub per import and write its address into the import address
    // table, which on EKA1 sits at the end of the code section.
    //   ldr r0, [pc, #0]   -> the report code
    //   ldr pc, [pc, #0]   -> gate6_report
    u32 *iat = (u32 *)(base + h->textSize);
    u8 *stub = base + h->codeSize;
    u8 *trace = stub + stubBytes;
    u32 forwarded = 0, missing = 0;

    Context *ctx = (Context *)user_allocz((int)sizeof(Context));
    if (!ctx) PANIC(CAT_MEM, -23);
    ctx->path = paths[chosen];
    ctx->pathLen = lens[chosen];
    ctx->pathIndex = (u32)chosen;
    ctx->codeBase = (u32)base;
    ctx->lastImport = 0xFFFF;               // nothing yet
    ctx->spare = trace + nImports * TRACE + 16 * TRACE;  // past the fixed thunks
    ctx->spareEnd = trace + traceBytes;

    ctx->cppRuntime = (u32)&drtaeabi_pure_virtual;

    {
        u32 *noop = (u32 *)(trace + nImports * TRACE + 10 * TRACE);
        noop[0] = 0xE3A00000;           // mov r0, #0
        noop[1] = 0xE12FFF1E;           // bx  lr
        user_imb_range(noop, noop + 2);
        ctx->noopFn = (u32)noop;
    }

    // Read what the last run got to, if it left anything this build wrote, and
    // say so. The file is armed again by replacing it rather than deleting it,
    // so that a delete the file server refuses cannot leave a stale record to
    // be reported over and over.
    {
        Ptrc16 name;
        box_name(&name);
        u32 magic = 0, last = BOX_NONE, reached = 0, count = 0;
        if (fs_connect(ctx->boxFs, -1) == 0) {
            if (file_open(ctx->boxFile, ctx->boxFs, &name, 1) == 0) {
                Ptr8 des;
                des.lengthAndType = (u32)EPtr << KTypeShift;
                des.maxLength = BOX_BYTES;
                des.ptr = (u8 *)ctx->boxData;
                for (int i = 0; i < BOX_WORDS; i++) ctx->boxData[i] = 0;
                file_read(ctx->boxFile, &des);
                rhandle_close(ctx->boxFile);
                magic = ctx->boxData[0];
                last = ctx->boxData[1];
                reached = ctx->boxData[2];
                count = ctx->boxData[3];
                box_report(ctx, count);
            }
            if (file_replace(ctx->boxFile, ctx->boxFs, &name, EFileWrite | EFileShareAny) == 0) {
                ctx->lastImport = BOX_ARMED;    // armed, nothing recorded yet
                box_flush(ctx);
                ctx->lastImport = 0xFFFF;
            }
            // One number, three fields. How many imports the game got through
            // says at a glance whether it is running or stopped: a few hundred
            // is a startup that gave up, thousands is a frame loop. Then which
            // import it was on -- three digits, and 999 means the file was
            // armed and nothing was ever written to it -- and last a digit for
            // what happened: 1 the frame loop ran, 2 it left, 4 it exited.
            if (magic == BOX_MAGIC) {
                const u32 fate = ((reached & REACHED_RUNL) ? 1u : 0u)
                               | ((reached & REACHED_LEAVE) ? 2u : 0u)
                               | ((reached & REACHED_EXIT) ? 4u : 0u);
                const u32 steps = count > 99999 ? 99999 : count;
                PANIC(CAT_BOX, (int)(steps * 10000 +
                                     (last == BOX_ARMED ? 999 : (last % 1000)) * 10 +
                                     fate));
            }
        }
    }

    // The handler takes a TExcType in r0 and has nowhere to keep the context,
    // so it arrives through a thunk of its own.
    {
        u32 *b = (u32 *)(trace + nImports * TRACE);
        b[0] = 0xE1A01000;                  // mov r1, r0   -- the exception type
        b[1] = 0xE59F0000;                  // ldr r0, [pc, #0]
        b[2] = 0xE59FF000;                  // ldr pc, [pc, #0]
        b[3] = (u32)ctx;
        b[4] = (u32)&gate6_fault;
        user_setexceptionhandler(b, 0xFFFFFFFF);

    }
    for (u32 i = 0; i < nImports; i++) {
        u32 *s = (u32 *)(stub + SLOT * i);
        s[0] = 0xE59F0000;                  // ldr r0, [pc, #0]  -> the report code
        s[1] = 0xE59FF000;                  // ldr pc, [pc, #0]  -> gate6_report
        s[2] = nImports * 1000 + i;
        s[3] = (u32)&gate6_report;
        iat[i] = (u32)s;

        const u32 entry = (i < kShimCount) ? kShimTable[i] : 0;
        const u32 kind = entry >> 24;
        if (!kind)
            continue;

        if (kind == KIND_LOCAL) {
            switch (entry & 0xFFFF) {
            case LOCAL_NEGSF2:
                s[0] = 0xE2200102;          // eor r0, r0, #0x80000000
                s[1] = 0xE12FFF1E;          // bx  lr
                break;
            case LOCAL_NOOP:                // an empty body: _Reserved slots, CBase
                s[0] = 0xE3A00000;          // mov r0, #0
                s[1] = 0xE12FFF1E;          // bx  lr
                break;
            case LOCAL_SELF:                // a constructor with nothing to do
                s[0] = 0xE12FFF1E;          // bx  lr     -- r0 is still the object
                break;
            case LOCAL_TRUE:                // a predicate that is always yes
                s[0] = 0xE3A00001;          // mov r0, #1
                s[1] = 0xE12FFF1E;          // bx  lr
                break;
            case LOCAL_TRAP_ENTER:          // TTrap::Trap(TInt&): first pass, no error
                s[0] = 0xE3A00000;          // mov r0, #0
                s[1] = 0xE5810000;          // str r0, [r1]
                s[2] = 0xE12FFF1E;          // bx  lr
                break;
            case LOCAL_TINT64_SET:          // TInt64 from a TInt: sign-extend
                s[0] = 0xE5801000;          // str r1, [r0]
                s[1] = 0xE1A02FC1;          // mov r2, r1, asr #31
                s[2] = 0xE5802004;          // str r2, [r0, #4]
                s[3] = 0xE12FFF1E;          // bx  lr     -- r0 is still the object
                break;
            case LOCAL_MEM_COMPARE:
                s[0] = 0xE51FF004;          // ldr pc, [pc, #-4]
                s[1] = (u32)&gate6_mem_compare;
                break;
            default:
                s[0] = 0xE51FF004;
                s[1] = (u32)&gate6_pure_virtual;
                break;
            }
            forwarded++;
            continue;
        }

        void *fn = rlibrary_lookup(&libs[(entry >> 16) & 0xFF], (int)(entry & 0xFFFF));
        if (!fn) {
            missing++;                      // the stub stays, so we hear about it
            continue;
        }
        if (kind == KIND_CALL) {
            iat[i] = (u32)fn;
        } else if (kind == KIND_SRET8) {
            // GCC98r2 returned an eight-byte structure in r0 and r1; EABI wants
            // a buffer in r0 and pushes `this` to r1. Borrow eight bytes of
            // stack, let the callee fill them, and hand them back in registers.
            s[0] = 0xE92D4010;              // push  {r4, lr}
            s[1] = 0xE24DD008;              // sub   sp, sp, #8
            s[2] = 0xE1A01000;              // mov   r1, r0      -- `this`
            s[3] = 0xE1A0000D;              // mov   r0, sp      -- the buffer
            s[4] = 0xE59F4008;              // ldr   r4, [pc, #8]
            s[5] = 0xE12FFF34;              // blx   r4
            s[6] = 0xE8BD0003;              // ldmia sp!, {r0, r1}
            s[7] = 0xE8BD8010;              // pop   {r4, pc}
            s[8] = (u32)fn;
        } else if (kind == KIND_ARGSHIFT) {
            // A member function 9.x made free: drop `this` and move the rest
            // down a register.
            s[0] = 0xE1A00001;              // mov r0, r1
            s[1] = 0xE1A01002;              // mov r1, r2
            s[2] = 0xE1A02003;              // mov r2, r3
            s[3] = 0xE51FF004;              // ldr pc, [pc, #-4]
            s[4] = (u32)fn;
        } else if (kind == KIND_ARG3) {
            s[0] = 0xE3A02000;              // mov r2, #0    -- the added argument
            s[1] = 0xE51FF004;              // ldr pc, [pc, #-4]
            s[2] = (u32)fn;
        } else {
            s[0] = 0xE92D4000;              // push {lr}
            s[1] = 0xE59FC008;              // ldr  r12, [pc, #8]
            s[2] = 0xE12FFF3C;              // blx  r12
            s[3] = 0xE1A00001;              // mov  r0, r1   -- the remainder
            s[4] = 0xE8BD8000;              // pop  {pc}
            s[5] = (u32)fn;
        }
        forwarded++;
    }
    if (!forwarded) PANIC(CAT_SHIM, (int)missing);

    // Keep avkon's handle: the app UI needs two things out of it that no
    // header will give us, and the shim's list is a local of this function.
    for (u32 i = 0; i < kShimDllCount; i++) {
        const u16 *nm = kShimDllName[i];
        if (kShimDllLen[i] >= 5 && nm[0] == 'a' && nm[1] == 'v' && nm[2] == 'k' &&
            nm[3] == 'o' && nm[4] == 'n') {
            ctx->avkon = libs[i];
            break;
        }
    }
    if (!ctx->avkon) PANIC(CAT_LIB, -100);

    // The stub slot of a resolved import is spare -- its address went straight
    // into the table -- so the diversions are built there.
    if (nImports <= IMPORT_BASECONSTRUCTL) PANIC(CAT_SHIM, (int)nImports);
    ctx->newBaseConstructL = iat[IMPORT_BASECONSTRUCTL];
    iat[IMPORT_BASECONSTRUCTL] = ctx_thunk(stub + SLOT * IMPORT_BASECONSTRUCTL,
                                           ctx, (u32)&gate6_baseconstructl);

    if (nImports > IMPORT_CREATEWINDOWL)
        iat[IMPORT_CREATEWINDOWL] = ctx_thunk(stub + SLOT * IMPORT_CREATEWINDOWL,
                                              ctx, (u32)&gate6_create_window);
    if (nImports > IMPORT_DLL_NAME)
        iat[IMPORT_DLL_NAME] = ctx_thunk(stub + SLOT * IMPORT_DLL_NAME,
                                         ctx, (u32)&gate6_dll_name);
    if (nImports > IMPORT_COEENV_STATIC)
        iat[IMPORT_COEENV_STATIC] = ctx_thunk(stub + SLOT * IMPORT_COEENV_STATIC,
                                              ctx, (u32)&gate6_coeenv_static);
    if (nImports > IMPORT_COECONTROL_CTOR)
        iat[IMPORT_COECONTROL_CTOR] = ctx_thunk(stub + SLOT * IMPORT_COECONTROL_CTOR,
                                                ctx, (u32)&gate6_coecontrol_ctor);
    if (nImports > IMPORT_WINDOW) {
        u32 *w = (u32 *)(stub + SLOT * IMPORT_WINDOW);
        w[0] = 0xE5900000 | OLD_CONTROL_WIN;    // ldr r0, [r0, #0x20]  -- iWin
        w[1] = 0xE12FFF1E;                      // bx  lr
        iat[IMPORT_WINDOW] = (u32)w;
    }
    if (nImports > IMPORT_ADDTOSTACKL && IMPORT_ADDTOSTACKL < kShimCount &&
        (kShimTable[IMPORT_ADDTOSTACKL] >> 24) == KIND_CALL)
        iat[IMPORT_ADDTOSTACKL] = pair_thunk(stub + SLOT * IMPORT_ADDTOSTACKL,
                                             &ctx->wrapUi, &ctx->wrapControl,
                                             iat[IMPORT_ADDTOSTACKL]);

    for (u32 k = 0; k < sizeof kDiverts / sizeof kDiverts[0]; k++) {
        const u32 j = kDiverts[k].import;
        // An import the shim could not answer keeps its reporting stub: sending
        // it through a diversion would lose the one thing it can still tell us.
        if (j >= nImports || j >= kShimCount || (kShimTable[j] >> 24) != KIND_CALL)
            continue;
        u32 **cell = &ctx->wrapUi;
        if (kDiverts[k].object == ON_CONTROL) cell = &ctx->wrapControl;
        else if (kDiverts[k].object == ON_TIMER) cell = &ctx->wrapTimer;
        else if (kDiverts[k].object == ON_GC) cell = &ctx->realGc;
        iat[j] = this_thunk(stub + SLOT * j, cell, iat[j], kDiverts[k].arg);
    }

    if (nImports > IMPORT_ADD_FOREGROUND_OBSERVER &&
        IMPORT_ADD_FOREGROUND_OBSERVER < kShimCount &&
        (kShimTable[IMPORT_ADD_FOREGROUND_OBSERVER] >> 24) == KIND_CALL) {
        u8 *spare = trace + nImports * TRACE;
        u32 *vt = (u32 *)user_allocz(FOREGROUND_SLOTS * 4);
        u32 *obs = (u32 *)user_allocz(4);
        if (!vt || !obs) PANIC(CAT_MEM, -36);
        vt[0] = ctx_thunk(spare + 13 * TRACE, ctx, (u32)&gate6_foreground_gaining);
        vt[1] = ctx_thunk(spare + 14 * TRACE, ctx, (u32)&gate6_foreground_losing);
        obs[0] = (u32)vt;
        iat[IMPORT_ADD_FOREGROUND_OBSERVER] =
            fg_thunk(spare + 15 * TRACE, &ctx->oldForeground, &ctx->coeEnv, obs,
                     iat[IMPORT_ADD_FOREGROUND_OBSERVER]);
    }

    // The window server's view of the game's observer.
    if (nImports > IMPORT_DSA_NEWL && IMPORT_DSA_NEWL < kShimCount &&
        (kShimTable[IMPORT_DSA_NEWL] >> 24) == KIND_CALL) {
        u8 *spare = trace + nImports * TRACE;
        u32 *vt = (u32 *)user_allocz(DSA_SLOTS * 4);
        u32 *obs = (u32 *)user_allocz(4);
        if (!vt || !obs) PANIC(CAT_MEM, -34);
        vt[0] = ctx_thunk(spare + TRACE, ctx, (u32)&gate6_dsa_slot0);
        vt[1] = ctx_thunk(spare + 2 * TRACE, ctx, (u32)&gate6_dsa_slot1);
        obs[0] = (u32)vt;               // 9.x: the vptr points at slot 0
        // The old-layout view of the object, and the old-vtable view of the
        // graphics context inside it.
        ctx->dsaShadow = (u32 *)user_allocz(OLD_DSA_BYTES);
        u32 *gcVt = (u32 *)user_allocz((2 + OLD_GC_SLOTS) * 4);
        ctx->fakeGc = (u32 *)user_allocz(4);
        if (!ctx->dsaShadow || !gcVt || !ctx->fakeGc) PANIC(CAT_MEM, -37);
        u8 *gcRoom = ctx->spare;
        if (gcRoom + OLD_GC_SLOTS * GC_THUNK_BYTES > ctx->spareEnd)
            PANIC(CAT_MEM, -38);
        for (u32 i = 0; i < OLD_GC_SLOTS; i++)
            gcVt[2 + i] = (kGcSlot[i] == GC_NONE)
                ? (u32)&gate6_pure_virtual
                : gc_thunk(gcRoom + i * GC_THUNK_BYTES, &ctx->realGc, kGcSlot[i]);
        if (!DRAW_THE_FRAME) {
            // Its thunk is already there and already pointed at; only what it
            // does changes.
            u32 *b = (u32 *)(gcRoom + OLD_GC_BITBLT * GC_THUNK_BYTES);
            b[0] = 0xE3A00000;          // mov r0, #0
            b[1] = 0xE12FFF1E;          // bx  lr
            user_imb_range(b, b + 2);
        }
        ctx->spare = gcRoom + OLD_GC_SLOTS * GC_THUNK_BYTES;
        // GCC98r2 keeps the two header words in the table and points at them.
        ctx->fakeGc[0] = (u32)gcVt;

        iat[IMPORT_DSA_NEWL] = dsa_thunk(spare + 8 * TRACE, &ctx->oldObserver, obs,
                                         iat[IMPORT_DSA_NEWL], &ctx->dsaReal,
                                         &ctx->dsaShadow);
        if (nImports > IMPORT_DSA_STARTL && IMPORT_DSA_STARTL < kShimCount &&
            (kShimTable[IMPORT_DSA_STARTL] >> 24) == KIND_CALL) {
            ctx->newDsaStartL = iat[IMPORT_DSA_STARTL];
            iat[IMPORT_DSA_STARTL] = ctx_thunk(stub + SLOT * IMPORT_DSA_STARTL,
                                               ctx, (u32)&gate6_dsa_startl);
        }
    }

    if (nImports > IMPORT_CANCEL && IMPORT_CANCEL < kShimCount &&
        (kShimTable[IMPORT_CANCEL] >> 24) == KIND_CALL) {
        ctx->newCancel = iat[IMPORT_CANCEL];
        iat[IMPORT_CANCEL] = ctx_thunk(stub + SLOT * IMPORT_CANCEL, ctx,
                                       (u32)&gate6_cancel);
    }

    if (nImports > IMPORT_LIBRARY_LOOKUP && IMPORT_LIBRARY_LOOKUP < kShimCount &&
        (kShimTable[IMPORT_LIBRARY_LOOKUP] >> 24) == KIND_CALL) {
        u32 *id = (u32 *)(trace + nImports * TRACE + 11 * TRACE);
        id[0] = 0xE3A00000;             // mov r0, #0
        id[1] = 0xE3A01000;             // mov r1, #0
        id[2] = 0xE12FFF1E;             // bx  lr
        ctx->idFn = (u32)id;
        ctx->writeFn = ctx3_thunk(trace + nImports * TRACE + 12 * TRACE, ctx,
                                  (u32)&gate6_write_memory);
        ctx->newLibraryLookup = iat[IMPORT_LIBRARY_LOOKUP];
        iat[IMPORT_LIBRARY_LOOKUP] = ctx_thunk(stub + SLOT * IMPORT_LIBRARY_LOOKUP,
                                               ctx, (u32)&gate6_library_lookup);
        if (nImports > IMPORT_LIBRARY_LOAD && IMPORT_LIBRARY_LOAD < kShimCount &&
            (kShimTable[IMPORT_LIBRARY_LOAD] >> 24) == KIND_CALL) {
            ctx->newLibraryLoad = iat[IMPORT_LIBRARY_LOAD];
            iat[IMPORT_LIBRARY_LOAD] = ctx3_thunk(stub + SLOT * IMPORT_LIBRARY_LOAD,
                                                  ctx, (u32)&gate6_library_load);
        }
    }

    if (nImports > IMPORT_REQUEST_COMPLETE && IMPORT_REQUEST_COMPLETE < kShimCount &&
        (kShimTable[IMPORT_REQUEST_COMPLETE] >> 24) == KIND_CALL) {
        ctx->newRequestComplete = iat[IMPORT_REQUEST_COMPLETE];
        iat[IMPORT_REQUEST_COMPLETE] =
            ctx_thunk(stub + SLOT * IMPORT_REQUEST_COMPLETE, ctx,
                      (u32)&gate6_request_complete);
    }

    // The scheduler's timer, and the game's.
    if (nImports > IMPORT_CTIMER_CTOR && IMPORT_CTIMER_CTOR < kShimCount &&
        (kShimTable[IMPORT_CTIMER_CTOR] >> 24) == KIND_CALL) {
        u8 *spare = trace + nImports * TRACE;
        ctx->newTimerCtor = iat[IMPORT_CTIMER_CTOR];
        ctx->timerThunks[0] = ctx_thunk(spare + 4 * TRACE, ctx, (u32)&gate6_timer_docancel);
        ctx->timerThunks[1] = ctx_thunk(spare + 5 * TRACE, ctx, (u32)&gate6_timer_runl);
        ctx->timerThunks[2] = ctx_thunk(spare + 6 * TRACE, ctx, (u32)&gate6_timer_runerror);
        iat[IMPORT_CTIMER_CTOR] = ctx_thunk(spare + 7 * TRACE, ctx, (u32)&gate6_ctimer_ctor);
    }

    if (!TAKE_THE_SCREEN) {
        if (nImports > IMPORT_SET_AUTO_UPDATE) iat[IMPORT_SET_AUTO_UPDATE] = ctx->noopFn;
        if (nImports > IMPORT_SCREEN_UPDATE) iat[IMPORT_SCREEN_UPDATE] = ctx->noopFn;
    }

    for (u32 i = 0; i < sizeof kCrumb / sizeof kCrumb[0]; i++)
        if (kCrumb[i] + 4 <= h->codeSize)
            crumb_plant(ctx, base, kCrumb[i], CRUMB_FIRST + i);

    // Last, so that it records every import however it ended up being answered.
    for (u32 i = 0; i < nImports; i++)
        iat[i] = trace_thunk(trace + TRACE * i, ctx, i, iat[i], (u32)&gate6_trace);

    // Everything above -- the image, the stubs, every thunk -- was written as
    // data and is about to be run as code, so the caches are put right over
    // the whole chunk before anything in it is entered.
    user_imb_range(base, base + chunkSize);

    // Enter it. EKA1 calls a DLL's entry point with EDllProcessAttach first,
    // then apparc asks ordinal 1 for the application object.
    typedef int (*EntryFn)(int);
    typedef void *(*Ordinal1Fn)(void);
    ((EntryFn)(base + h->entryPoint))(0);
    const u32 ord1 = *(const u32 *)(raw + h->exportDirOffset);
    void *app = ((Ordinal1Fn)(base + ord1))();
    if (!app) PANIC(CAT_NUL, (int)(forwarded * 1000 + missing));
    // The 9.x application: built the ordinary way, then told which old object
    // it stands for, with its two overridden slots pointed at the game.
    u32 *wrap = (u32 *)user_allocz(WRAP_BYTES);
    if (!wrap) PANIC(CAT_MEM, -20);
    eikapplication_ctor(wrap);
    wrap[WRAP_OLD] = (u32)app;
    wrap[WRAP_CTX] = (u32)ctx;

    u32 *vt = copy_vtable(vtable_of(wrap), APP_SLOTS);
    vt[VT_HEADER + SLOT_APP_DLL_UID] = (u32)&gate6_app_dll_uid;
    vt[VT_HEADER + SLOT_CREATE_DOCUMENT] = (u32)&gate6_create_document;
    instrument(ctx, vt, APP_SLOTS, OBJ_APP);
    wrap[0] = (u32)(vt + VT_HEADER);
    return (u32)wrap;

}
